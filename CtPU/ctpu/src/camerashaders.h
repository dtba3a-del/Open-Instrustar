#pragma once

#include <QSize>
#include <QSizeF>
#include <QString>

/// \brief Исходники шейдера слоя камеры и нормализация кадра на фон.
///
/// Зачем отдельный файл. Прежняя редакция собирала исходник как
/// `GLSLversion + "attribute highp vec3 vertex;…"`, а `GLSLversion` (см.
/// `glscope.h`) — это МЕТКА диалекта: `"1.50"`, `"1.20"`, `"1.00 ES"`, а не
/// директива `#version`. Исходник начинался строкой `1.50attribute highp vec3
/// vertex;` и не компилировался НИ ПРИ КАКОЙ конфигурации: программа не
/// линковалась, `drawCameraLayer()` выходил на первом условии, и кадра на
/// холсте не было никогда. Дефект не давал ни отказа сборки, ни отказа
/// запуска — только `qWarning` в поток, которого оператор не видит.
///
/// Вынесено сюда потому, что построение исходника проверяется тестом БЕЗ
/// контекста OpenGL: на сборочной машине графики нет, а именно построение и
/// сломалось. Проверять то, что нельзя выполнить, — по тексту.
/// \name Метки диалекта GLSL
///
/// Живут здесь, а не в `glscope.h`, потому что диалект выбирают ДВА места —
/// основная программа и программа слоя камеры, — а решать это должно одно.
/// `glscope.h` подключает этот заголовок и метками пользуется.
///@{
#define GLES100 "1.00 ES"
#define GLSL120 "1.20"
#define GLSL150 "1.50"
///@}

namespace CameraShaders {

    /// Пара исходников одной программы.
    struct Sources {
        QString vertex;
        QString fragment;
    };

    /// \brief Исходники под диалект, названный меткой из `glscope.h`.
    /// \param glslVersion `GLES100` / `GLSL120` / `GLSL150`; при незнакомом
    ///        значении выдаются исходники 1.20 — самый широкий из трёх.
    Sources forGlslVersion( const QString &glslVersion );

    /// \brief Доля холста, которую занимает кадр, без искажения пропорций.
    ///
    /// Задача автора 2026-09-02: «размер изображения камеры может быть разный…
    /// от 0,31 Mp до 40 Mp и это нужно нормализовать на не фиксированный
    /// размер фона». Фон — холст, его размер меняется вместе с окном, поэтому
    /// множитель считается на каждый кадр и на каждое изменение размера.
    ///
    /// Кадр вписывается ЦЕЛИКОМ и с сохранением пропорций: растянуть кадр по
    /// холсту значило бы показать оператору предмет искажённым, а он смотрит
    /// сквозь этот слой на плату. Одна из двух долей всегда равна 1.0.
    ///
    /// \returns множители по X и Y в долях холста; при негодных размерах —
    ///          (1, 1), то есть «во всё поле».
    QSizeF fitScale( const QSize &frame, const QSize &canvas );

    /// \brief Размер, до которого уменьшается кадр перед выгрузкой в текстуру.
    ///
    /// Смысл — не красота, а работоспособность: кадр 40 Mp это ~7300×5500, и
    /// он (а) перекладывается в текстуру на каждом кадре, (б) у части
    /// драйверов превышает `GL_MAX_TEXTURE_SIZE` — тогда текстура не создаётся
    /// и слоя опять нет. Больше пикселей, чем есть на холсте, показать нельзя
    /// по построению, поэтому уменьшение ничего не теряет.
    ///
    /// \param maxTextureSize предел драйвера; 0 — предел неизвестен.
    /// \returns размер для `QImage::scaled`; пустой размер — «не уменьшать».
    QSize normalizedFrameSize( const QSize &frame, const QSize &canvas, int maxTextureSize );

} // namespace CameraShaders
