// MedianFilter — нелинейный предфильтр против коммутационных помех и звона.
//
// Зачем отдельно от MovingAverage (movingaverage.h):
//   Скользящее среднее — линейное, оно ВКЛЮЧАЕТ выброс в результат
//   (один импульс амплитудой A в окне N сдвигает выход на A/N и «размазывает»
//   его на N отсчётов). Медиана импульс просто ВЫБРАСЫВАЕТ, если он занимает
//   меньше половины окна, и при этом не заваливает фронты — именно поэтому
//   для коммутационных помех/звона нужен именно медианный фильтр, а не ещё
//   одно усреднение.
//
// Место в тракте (решение согласовано в чате):
//   сырые сэмплы -> MedianFilter (опция) -> бинирование -> статистики бина
//   Медиана здесь — СТАДИЯ ОБРАБОТКИ, а не выходная величина. Это снимает
//   принципиальную проблему: медиана не сливается точно при объединении
//   бинов (медиана медиан != медиана), поэтому как экспортируемая
//   характеристика она была бы ложью, а как предфильтр — совершенно
//   корректна.
//
// Важный побочный эффект, ради которого это и нужно бинам:
//   min/max бина (envelope) — главная жертва одиночного выброса: один звон
//   задирает max навсегда, и никакое последующее слияние это не исправит.
//   После медианного предфильтра envelope снова означает реальный охват
//   сигнала, а не «где однажды стрельнуло».
//
// Стоимость: O(n * log W) при сортировке окна; W берут небольшим (5..61).
// При W <= 1 — тождественная функция (быстрый путь, ничего не копируется).

#pragma once

#include <algorithm>
#include <cmath>
#include <cstdint>
#include <vector>

namespace MedianFilter {

/// \brief Скользящая медиана с центрированным окном ширины W.
///
/// В отличие от MovingAverage::apply(), длина результата РАВНА длине входа:
/// у краёв окно просто усекается (обрабатывается по тем отсчётам, что есть).
/// Так сделано намеренно — этот фильтр стоит в тракте до бинирования, и
/// укорачивание записи на каждом проходе было бы неудобным и неочевидным
/// для вызывающего кода; краевой эффект медианы (усечённое окно) намного
/// безобиднее, чем сдвиг индексов.
///
/// W чётное -> используется W+1 (медиана определена однозначно только для
/// нечётного размера окна; иначе пришлось бы усреднять два средних значения,
/// то есть протаскивать обратно ровно ту линейность, от которой уходим).
static inline std::vector< double > apply( const std::vector< double > &in, unsigned W ) {
    if ( W <= 1 || in.size() < 2 )
        return in;
    if ( ( W & 1u ) == 0u )
        ++W; // всегда нечётное окно
    const std::size_t n = in.size();
    const std::size_t half = W / 2;

    std::vector< double > out( n );
    std::vector< double > window;
    window.reserve( W );

    for ( std::size_t i = 0; i < n; ++i ) {
        const std::size_t lo = ( i > half ) ? i - half : 0;
        const std::size_t hi = std::min( n, i + half + 1 ); // [lo, hi)
        window.assign( in.begin() + long( lo ), in.begin() + long( hi ) );
        const std::size_t mid = window.size() / 2;
        std::nth_element( window.begin(), window.begin() + long( mid ), window.end() );
        out[ i ] = window[ mid ];
    }
    return out;
}

/// \brief То же самое, но с УЧЁТОМ вмешательства фильтра.
///
/// Зачем: баланс не должен иметь неопределённой недостачи. Важная тонкость —
/// медиана НЕ выбрасывает отсчёты: длина выхода равна длине входа, по
/// количеству недостачи не возникает в принципе. Фильтр ПОДМЕНЯЕТ ЗНАЧЕНИЕ
/// там, где распознал выброс. Поэтому честный предмет учёта — сколько
/// отсчётов он изменил и на какую суммарную величину:
///   modified   — сколько значений отличаются от исходных (|out-in| > eps)
///   absCorrect — сумма |out-in| по всем отсчётам (насколько всего вмешался)
/// Обе величины аддитивны, поэтому точно суммируются при слиянии бинов.
///
/// Большой modified означает: либо в сигнале действительно много выбросов,
/// либо окно W выбрано слишком агрессивным и режет полезную структуру.
/// Различить это можно, сравнив absCorrect с амплитудой сигнала. Главное —
/// цифра видна, а не скрыта.
///
/// eps: порог «значение изменилось». По умолчанию 0 — строгое сравнение,
/// корректно для случая, когда медиана вернула буквально один из исходных
/// отсчётов окна (что она всегда и делает при нечётном окне).
static inline std::vector< double > applyCounted( const std::vector< double > &in, unsigned W,
                                                   std::uint64_t &modified, double &absCorrect, double eps = 0.0 ) {
    modified = 0;
    absCorrect = 0.0;
    std::vector< double > out = apply( in, W );
    if ( out.size() != in.size() ) // не должно случаться, apply() сохраняет длину
        return out;
    for ( std::size_t i = 0; i < in.size(); ++i ) {
        const double d = std::fabs( out[ i ] - in[ i ] );
        if ( d > eps ) {
            ++modified;
            absCorrect += d;
        }
    }
    return out;
}

} // namespace MedianFilter
