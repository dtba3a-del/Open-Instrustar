#pragma once

#define DIVS_TIME 10.0   ///< Number of horizontal screen divs
#define DIVS_VOLTAGE 8.0 ///< Number of vertical screen divs
#define DIVS_SUB 5       ///< Number of sub-divisions per div

#define MARGIN_LEFT ( -DIVS_TIME / 2.0 )
#define MARGIN_RIGHT ( DIVS_TIME / 2.0 )
#define MARGIN_TOP ( DIVS_VOLTAGE / 2.0 )
#define MARGIN_BOTTOM ( -DIVS_VOLTAGE / 2.0 )

/// \brief Предел хода ползунка вертикального смещения, в делениях.
///
/// НЕ равен половине экрана. Смещение здесь чисто программное: рабочая точка
/// входного каскада жёстко привязана к GND, двигается только ИЗОБРАЖЕНИЕ, а
/// традиционный лимит ±DIVS_VOLTAGE/2 унаследован от приборов, где offset
/// смещает аналоговый тракт и увести трассу за экран поэтому невозможно.
///
/// НОРМАТИВ: полный ход ползунка — ТРИ ВЫСОТЫ ЭКРАНА (±1.5*DIVS_VOLTAGE).
/// Ровно столько нужно, чтобы поставить самый нижний уровень сигнала к
/// верхней кромке экрана, а самый верхний — к нижней, то есть осмотреть
/// любую часть сигнала в любом месте сетки. Меньше — останутся недостижимые
/// положения; больше — трасса просто уходит в никуда.
///
/// Практические случаи, где старого лимита ±4 деления НЕ ХВАТАЛО, хотя
/// данные корректны и аппаратно НЕ клиппированы (result.clipped взводится
/// только по сырым 0x00/0xFF в hantekdsocontrol.cpp):
///   - AC-связь (аппаратная, ControlSetCoupling): после снятия постоянной
///     составляющей равновесие на экране другое, и регулятора переставало
///     хватать там, где в DC тот же сигнал был виден полностью;
///   - math-каналы (M1 = CH1 + CH2 и т.п.) достигают ±DIVS_VOLTAGE делений;
///   - CtPU-каналы после k*x+b масштабируются произвольно и к сетке в 8
///     делений не привязаны вовсе.
/// Во всех случаях сигнал выглядел обрезанным при отсутствии обрезки.
///
/// Это лимит ХОДА ПОЛЗУНКА, а не данных: он ничего не ограничивает
/// физически и не стоит ничего, кроме диапазона регулировки.
#define OFFSET_LIMIT_DIVS ( DIVS_VOLTAGE * 1.5 )

#define MARKER_STEP ( DIVS_TIME / 100.0 )
