#pragma once

/// \file transport.h
/// \brief Транспорт — оснастка прибора, а не его порода.
///
/// ПОЧЕМУ СОСТАВОМ, А НЕ НАСЛЕДОВАНИЕМ
///
/// Первая редакция дерева задавала транспорт базовым классом: прибор
/// наследовал «последовательный» или «USB». Это неверно, и связка даёт три
/// встречных примера сразу:
///
///   * **ISDS205B** — путь B (fx2lafw + libusb) и путь A (вендорский
///     `vdso.dll`). Один прибор, два стека доступа; их разграничение —
///     самое дорогое правило проекта (`docs/ACCESS_PATHS.md`).
///   * **Oscill** — виртуальный COM-порт (CP2102 VCP) **или** Bluetooth SPP.
///   * **Е7-12** — адаптер UsbGpib **или** NI-VISA.
///
/// При наследовании каждый такой случай порождает второй класс прибора с
/// тем же разбором протокола — то есть удвоение кода на каждую шину. При
/// составе прибор один, а оснастка подставляется.
///
/// ЧТО ЗДЕСЬ НАМЕРЕННО ОТСУТСТВУЕТ
///
/// **Таймаутов и пауз в интерфейсе нет.** Не из аккуратности: у Е7-12
/// обмен по ГОСТ 26.003-80 квитируется сигналами шины, и понятия времени у
/// него не существует вовсе. Транспорт, у которого в контракте стоит
/// `timeout`, навязывает такому прибору чужую модель поведения. Транспорт,
/// которому таймаут нужен (последовательный порт), держит его у себя, а
/// наверх не выносит.
///
/// РАСЧЁТ НА ДЮЖИНУ ПРИБОРОВ
///
/// Третий прибор не последний, и никто не обещает, что следующий интерфейс
/// будет разумным. Поэтому правило: **вся придурь остаётся в бэкенде и в
/// транспорте**, наверх выходят только способности. Что бы прибор ни
/// вытворял на шине, приложение видит либо осциллограмму, либо показание,
/// либо привод — либо честное отсутствие способности.

#include <QByteArray>
#include <QString>
#include <memory>

namespace Instrument {

/// Как прибор физически подключён. Номер стабилен: он попадает в
/// сохранённые настройки слота.
enum class Bus : int {
    None = 0,
    Serial = 1,    ///< COM / VCP / Bluetooth SPP — байтовый поток
    UsbBulk = 2,   ///< libusb, конечные точки (путь B: fx2lafw)
    UsbTmc = 3,    ///< USBTMC / VISA, шина КОП через адаптер
    VendorDll = 4, ///< вендорская библиотека (путь A: vdso.dll)
    File = 5,      ///< воспроизведение записи вместо живой шины
};

/// \brief Оснастка: открыть, закрыть, обменяться.
///
/// Обмен намеренно описан двумя способами, потому что шины связки устроены
/// по-разному и сведение их к одному способу было бы враньём:
///   * `write`/`read` — байтовый поток (последовательный порт, USB bulk);
///   * `exchange` — одна транзакция «отдал — принял», квитируемая самой
///     шиной (USBTMC/КОП, вендорская библиотека).
/// Транспорт реализует то, что у него есть; неподдержанное честно
/// возвращает false, а не притворяется.
class Transport {
  public:
    virtual ~Transport() = default;

    virtual Bus bus() const = 0;
    virtual QString description() const = 0; ///< «COM3 115200», «USB 1d50:608e», «КОП:6»

    virtual bool open() = 0;
    virtual void close() = 0;
    virtual bool isOpen() const = 0;

    /// Байтовый поток. По умолчанию не поддержан.
    virtual bool write( const QByteArray & ) { return false; }
    virtual QByteArray read( int /*maxBytes*/ ) { return {}; }

    /// Одна транзакция. По умолчанию не поддержана.
    /// Возврат false — ошибка обмена; пустой ответ при true — законное
    /// состояние «прибору нечего сказать», а не сбой.
    virtual bool exchange( const QByteArray & /*out*/, QByteArray & /*in*/ ) { return false; }

    /// Последняя ошибка шины; пусто, если ошибок не было.
    const QString &lastError() const { return m_lastError; }

  protected:
    QString m_lastError;
};

using TransportPtr = std::unique_ptr< Transport >;

} // namespace Instrument
