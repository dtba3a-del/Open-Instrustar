#pragma once

/// \file serialtransport.h
/// \brief Последовательный порт как оснастка прибора: COM/VCP и Bluetooth SPP.
///
/// ПОЧЕМУ ПИШЕТСЯ СВОЙ, А НЕ БЕРЁТСЯ ГОТОВЫЙ
///
/// `Qt5SerialPort` в сборке проекта нет, и добавлять зависимость нельзя:
/// сборочная цель — MSYS2 MinGW64 с уже определённым составом модулей Qt,
/// а новый `find_package` пришлось бы объявлять и приложению, и тестам —
/// ровно тот случай двоевластия, который ловит хук перед сборкой
/// (`docs/ДВОЕВЛАСТИЕ.md`). Порт нужен один и простой: открыть, задать
/// скорость и таймауты, читать и писать байты. Этого хватает на Win32
/// (`CreateFileW` / `SetCommState` / `SetCommTimeouts` / `ReadFile` /
/// `WriteFile`) и на POSIX (`open` / `termios` / `read` / `write`).
///
/// ЗАГОЛОВОК ОБЯЗАН БЫТЬ ПЛАТФОРМОНЕЗАВИСИМЫМ
///
/// Прототип целится в Windows 11 x64, но собирается и проверяется этот
/// код на машине разработчика. Если в заголовок протечёт `windows.h` или
/// `termios.h`, тесты перестанут собираться на одной из двух машин — и
/// перестанут именно те тесты, ради которых транспорт отделён от кодека.
/// Поэтому платформенная часть спрятана целиком: здесь только
/// `struct Impl;` без определения, а `#ifdef _WIN32` живёт в `.cpp`.
/// Отсюда же объявленный, но не определённый здесь деструктор: без него
/// `std::unique_ptr` неполного типа не соберётся.
///
/// ЧЕГО ЗДЕСЬ НЕТ И ПОЧЕМУ
///
///   * **`exchange()` не переопределяется.** Транзакция «отдал — принял»
///     у OBEX собирается выше: одна логическая транзакция может занять
///     десяток пакетов (`0x90 Continue`), а сколько их будет — знает
///     бэкенд, а не порт. Наследуемая реализация честно вернёт false.
///   * **Разбора протокола нет ни байта.** Порт не знает, что такое
///     пакет; он отдаёт то, что пришло.
///   * **Таймауты наружу не выносятся.** Контракт `Instrument::Transport`
///     их не имеет намеренно — прибор с квитируемой шиной (Е7-12) не
///     знает понятия времени вовсе. Порт держит свои таймауты у себя, в
///     `SerialParams`, и это его частное дело.
///
/// СОСТОЯНИЕ УТВЕРЖДЕНИЙ. Прибора Oscill в работе нет: числа скоростей и
/// таймаутов здесь — **[СБОРКА]**, проверены сборкой и прогоном против
/// поддельного порта, но не на живой линии.

#include "../transport.h"

#include <QByteArray>
#include <QString>

#include <memory>
#include <vector>

namespace Instrument {

/// \brief Параметры линии. Единственное место, где они заданы.
///
/// Скорость держится ЗДЕСЬ, а не отдельным полем класса: у величины одно
/// место, которое её порождает. `setBaudRate()` меняет именно это поле,
/// и `description()` печатает именно его — расхождения «в описании 9600,
/// на линии 115200» по построению не будет.
struct SerialParams {
    /// «COM3», «\\\\.\\COM12» для номеров выше девятого, «/dev/ttyUSB0»,
    /// «/dev/rfcomm0» для Bluetooth SPP.
    QString port;
    /// Сессия OBEX с Oscill по первоисточнику начинается на 9600 бод;
    /// обе эталонные реализации открывают порт сразу на 115200 и команду
    /// смены скорости не шлют вовсе. Противоречие на бумаге не
    /// закрывается — значение задаёт вызывающий, умолчания нет. [СБОРКА]
    int baudRate = 0;
    /// Сколько ждать ПЕРВОГО байта ответа. Ноль означает «не ждать
    /// вовсе»: чтение возвращает то, что уже лежит в буфере. Это не
    /// вырожденный случай, а рабочий — на нём стоит неблокирующий шаг
    /// опроса бэкенда.
    int readTimeoutMs = 0;
    /// Сколько ждать СЛЕДУЮЩЕГО байта внутри начавшегося ответа. Пакет
    /// OBEX приходит одной очередью; молчание дольше этого срока значит,
    /// что очередь кончилась, а не что линия медленная.
    int interByteTimeoutMs = 20;
    /// Сколько ждать завершения записи. Запись в порт блокируется редко,
    /// но повиснуть навсегда она не должна: связка ждёт быстрый прибор.
    int writeTimeoutMs = 500;
};

/// \brief Байтовый поток последовательного порта.
///
/// Класс окончательный: наследовать от него нечего — различие COM/VCP и
/// Bluetooth SPP на уровне байтов отсутствует и уходит в
/// `description()`, как и предписывает контракт транспорта.
class SerialTransport final : public Transport {
  public:
    explicit SerialTransport( SerialParams params );
    ~SerialTransport() override;

    SerialTransport( const SerialTransport & ) = delete;
    SerialTransport &operator=( const SerialTransport & ) = delete;

    // --- Instrument::Transport ---

    /// Всегда `Bus::Serial`: и виртуальный COM-порт преобразователя
    /// CP210x, и Bluetooth SPP суть один и тот же байтовый поток.
    Bus bus() const override;

    /// «COM3 115200», «/dev/rfcomm0 9600 (SPP)». Строка идёт в
    /// `State::transport` и показывается пользователю: по ней он должен
    /// узнать, ЧТО именно сейчас открыто.
    QString description() const override;

    bool open() override;
    void close() override;
    bool isOpen() const override;

    /// Записать целиком. false — записано не всё или порт закрыт;
    /// частичная запись пакета OBEX бессмысленна, поэтому «сколько
    /// удалось» наружу не выдаётся.
    bool write( const QByteArray &data ) override;

    /// Прочитать НЕ БОЛЕЕ `maxBytes` из того, что уже пришло, с учётом
    /// `readTimeoutMs`. Пустой результат при открытом порте — законное
    /// состояние «прибор пока молчит», а не ошибка: правило
    /// первоисточника «ноль байт есть отсутствие ответа, один байт есть
    /// ответ» строится ровно на этом различии, и склеивать их нельзя.
    QByteArray read( int maxBytes ) override;

    // --- Сверх контракта: то, что нужно именно последовательной линии ---

    /// Сколько байт уже лежит в приёмном буфере, не забирая их.
    /// Отрицательное значение — порт закрыт или опрос не удался; ноль и
    /// «не смог спросить» — разные исходы.
    int bytesAvailable() const;

    /// Читать, пока не наберётся ровно `count` байт или не истечёт
    /// `timeoutMs`. Возвращает то, что успело прийти, — короткий
    /// результат означает «пакет не дочитан», и решает это вызывающий.
    QByteArray readExactly( int count, int timeoutMs );

    /// Выбросить всё, что накопилось в приёмном (и передающем) буфере.
    /// Нужно после сброса `Abort`: прибор в этот момент может дописывать
    /// хвост прежнего ответа, и этот хвост нельзя принять за начало
    /// нового пакета.
    void purge();

    /// Сменить скорость на ОТКРЫТОМ порту. Меняет только свою сторону
    /// линии: у прибора скорость меняется его собственной командой, и
    /// порядок двух действий задаёт бэкенд, а не порт. false — порт
    /// закрыт, скорость неприемлема системой или установка не удалась.
    bool setBaudRate( int baud );

    /// Действующие параметры линии.
    const SerialParams &params() const;
    int baudRate() const { return params().baudRate; }

    /// Есть ли такой порт в системе. Для `probe()`: спрашивается, НЕ
    /// открывая порт, — открытие чужого занятого COM-порта есть
    /// вмешательство, а `probe()` ничего менять не вправе.
    static bool exists( const QString &port );

    /// Порты, которые система показывает сейчас. Пустой список означает
    /// «ни одного не найдено», а не ошибку перечисления.
    static std::vector< QString > enumerate();

  private:
    /// Платформенная часть целиком: дескриптор, `DCB`/`termios`,
    /// перечисление портов. Определена в `.cpp` под `#ifdef _WIN32`.
    struct Impl;
    std::unique_ptr< Impl > m_impl;
};

/// Скорости, на которых сессия с Oscill имеет смысл. Ряд короткий
/// намеренно: коэффициент делителя прибора целочисленный, и произвольная
/// скорость даёт расхождение частот. `9600` — объявленное первоисточником
/// начало сессии, `115200` — то, на чём фактически работают обе эталонные
/// реализации, `921600` — предел, объявленный их же константой. [СБОРКА]
namespace SerialSpeeds {
constexpr int SESSION_START = 9600;
constexpr int WORK = 115200;
constexpr int FAST = 921600;
} // namespace SerialSpeeds

} // namespace Instrument
