/// Свойство прибора. Свойства только читаются: они описывают, что прибор
/// умеет, и меняются лишь как следствие записи регистров. [СБОРКА]
///
/// ДВА НЕПЕРЕСЕКАЮЩИХСЯ СПИСКА ВЕРСИЙ. Эталонный код спрашивает
/// `VNM/VSN/VHW/VSW` (имя, серийный номер, версия аппаратуры, версия ПО);
/// конспект протокола вместо них перечисляет шесть версий узлов
/// `VHD/VHA/VSD/VSI/VSC/VSO`, которых код не спрашивает ни разу. Оба
/// списка объявлены здесь целиком: какой из них поддержан прибором,
/// показывает ответ `0xD1` на остальные — то есть выясняется опросом,
/// а не выбором на бумаге.
enum class Property : int {
    // Паспорт прибора: 4 байта ASCII каждое
    VNM, ///< идентификатор (имя) прибора
    VSN, ///< серийный номер
    VHW, ///< версия аппаратной части
    VSW, ///< версия встроенного ПО
    // Версии узлов из конспекта протокола: 4 байта ASCII, формат X.XX
    VHD, ///< цифровая часть
    VHA, ///< аналоговая часть
    VSD, ///< оцифровщик
    VSI, ///< интерфейс пользователя
    VSC, ///< коннектор
    VSO, ///< модуль OBEX
    // Времязадающая часть
    MCd, ///< 2 б; машинный такт по умолчанию, ед. 10 пс (0x07D0 = 20 нс = 50 МГц)
    MCl, ///< 2 б; минимальный машинный такт («разгон»), ед. 10 пс (0x03E8 = 100 МГц)
    TOl, ///< 2 б; минимальный период однократной (realtime) дискретизации, такты×256
    TOv, ///< 4 б; битовая карта быстрых realtime-вариантов (см. fastRealtimeTicks)
    TMl, ///< 2 б; минимальный период стробоскопической (RIS) дискретизации, такты×256
    TMh, ///< 2 б; максимальный период RIS, такты×256
    TPl, ///< 4 б; минимальный период параллельной/бесконечной оцифровки, такты×256
    TCh, ///< 2 б; максимум предвыборок до синхронизации, ед. «выборка»
    QSh, ///< 2 б; максимальный размер выходного массива, ед. «выборка»
    TDl, ///< 4 б; минимальная задержка развёртки, ед. 12 тактов
    TDh, ///< 4 б; максимальная задержка развёртки, ед. 12 тактов
    // Канал
    V1h, ///< 2 б; НИЗШАЯ чувствительность, мВ/дел (0x2710 = 10000 = 10 В/дел)
    V1l, ///< 2 б; наивысшая чувствительность, мВ/дел (0x0014 = 20 мВ/дел)
    P1h, ///< 2 б ЗНАКОВОЕ; максимальное положительное смещение, ед. 1/256 диапазона АЦП
    P1l, ///< 2 б ЗНАКОВОЕ; максимальное отрицательное смещение
    D1m, ///< 2 б; конструктивная задержка компаратора синхронизации, ед. 10 пс
};

/// Объявление свойства. Ширина — сколько байт значение занимает в
/// заголовке ответа; ASCII-свойства приходят четырьмя байтами текста.
struct PropertyDef {
    const char *name;  ///< ровно 3 символа ASCII
    uint8_t width;     ///< 2 или 4
    bool isSigned;     ///< знаковое 16-битное разворачивать как (v<<16)>>16
    bool isAscii;      ///< значение — текст, а не число
    const char *unit;  ///< «10 пс», «такты×256», «выборка», «мВ/дел», «1/256 АЦП»; пусто — безразмерное
};

const PropertyDef &propertyDef( Property p );
inline const char *propertyName( Property p ) { return propertyDef( p ).name; }
/// Все объявленные свойства в порядке перечисления — для чтения паспорта.
const std::vector< Property > &allProperties();

/// Разбор карты `TOv`: какие периоды однократной дискретизации прибор
/// умеет быстрее предела `TOl`. Раскладка первоисточника: байт 0 биты
/// 7…0 = (—, 30, 29, 28, 27, 26, 25, 24) тактов на выборку; байт 1 =
/// (23…16); байт 2 = (15…8); байт 3 = (7, 6, 5, 4, 3, 2, 1, 1/2).
/// Половина такта представлена нулём: целых «полтактов» не бывает, и
/// вызывающий обязан различать 0 и 1. Первоисточник объявляет свойство
/// четырёхбайтовым, а пример приводит двухбайтовый — поэтому короткое
/// значение дополняется старшими нулями, а не отвергается. [СБОРКА]
std::vector< uint8_t > fastRealtimeTicks( uint32_t tov );

