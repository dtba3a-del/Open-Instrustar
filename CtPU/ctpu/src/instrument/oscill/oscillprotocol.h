/// \brief Есть ли в кадре поле размера массива. **На приборе не
/// проверено, выбирается опытом, а не бумагой.**
///
/// Первоисточник и конспект утверждают, что на каждый канал идут 2 байта
/// атрибутов, 2 байта размера массива в байтах и сам массив. Эталонная
/// реализация на Java утверждает обратное — «уже нет этого размера», —
/// берёт заголовок кадра ровно четырёхбайтовым и работала так с живым
/// прибором. Более поздняя реализация на Python размер читает, но живьём
/// её никто не проверял.
///
/// Разрешается первым же кадром: прочитать `uint16` big-endian по
/// смещению 4; если оно равно `размер тела − 6`, поле есть. Решение
/// принимается ОДИН раз, запоминается и печатается в журнал. [СБОРКА]
enum class FrameLayout : int {
    Unknown = 0,      ///< ещё ни одного кадра не разобрано
    WithSizeField,    ///< [attr:2][ch:2][size:2][data]
    WithoutSizeField, ///< [attr:2][ch:2][data] — раскладка Java
};

/// Источник запуска, биты 5-4 первого байта атрибутов оцифровки. [СБОРКА]
enum class TriggerSource : uint8_t {
    Timeout = 0b00,  ///< синхронизации не было, оцифровка запущена по TA
    Fall = 0b01,
    Rise = 0b10,
    Undefined = 0b11,///< комбинация первоисточником не определена
};

const char *triggerSourceName( TriggerSource t );

/// Данные одного канала кадра.
struct ChannelData {
    SampleFormat format = SampleFormat::Normal;
    bool formatKnown = false;   ///< false — биты 2-0 не совпали ни с одним форматом
    QByteArray raw;             ///< массив как пришёл, до распаковки
    std::vector< int > sample;  ///< коды; при огибающей — МИНИМУМЫ
    std::vector< int > sampleMax; ///< максимумы; непусто только при envelope
    bool envelope = false;      ///< PeakPaired: пара min,max на одну позицию времени
};

/// \brief Разобранный кадр вместе со своим аппаратным состоянием.
///
/// П1 связки: данные несут своё состояние. Атрибуты не выбрасываются
/// после разбора — они выходят из бэкенда ВМЕСТЕ с кадром, потому что
/// «10 делений от края» и «10 делений от края при пределе 1 В без
/// синхронизации» — разные сведения.
struct Frame {
    bool valid = false; ///< тело разобрано целиком и согласовано
    /// П2: ПУСТОЙ кадр. Ждущий запуск, `TW` истёк — прибор отвечает
    /// Success с пустым заголовком `0x49`. Данных нет, СВЯЗЬ ЦЕЛА, и это
    /// не ошибка. Отличие от «не синхронизировано» проходит по длине
    /// тела, а не по битам 5-4. [СБОРКА]
    bool empty = false;

    bool ris = false;      ///< бит 0 атрибутов: стробоскопическая оцифровка
    bool parallel = false; ///< бит 1: массив передаётся в процессе оцифровки
    bool roll = false;     ///< бит 2: бесконечная передача до Abort
    TriggerSource trigger = TriggerSource::Timeout;
    unsigned channels = 0;
    FrameLayout layout = FrameLayout::Unknown;
    std::vector< ChannelData > channel;

    /// П2, вторая половина: запуск по таймауту означает, что оцифровка
    /// СОСТОЯЛАСЬ и данные годны — они просто не привязаны к событию
    /// синхронизации. Такой кадр показывают с пометкой, а не прячут.
    bool synchronized() const {
        return trigger == TriggerSource::Fall || trigger == TriggerSource::Rise;
    }
};

/// Определить раскладку по первому кадру. `channels` — сколько каналов
/// объявлено атрибутами оцифровки. `Unknown` на выходе означает, что
/// опыт не разрешил вопрос (тело слишком короткое или обе раскладки
/// согласованы) — тогда решение принимает вызывающий и записывает его в
/// журнал явно. [СБОРКА]
FrameLayout detectLayout( const QByteArray &body, unsigned channels );

/// Разбор тела `0x49`. Пустое тело даёт `valid = true, empty = true`:
/// это штатный ответ ждущего запуска, а не отказ разбора. Раскладка
/// `Unknown` на входе заставляет функцию определить её самой и записать
/// в `out.layout`. [СБОРКА]
bool parseFrame( const QByteArray &body, FrameLayout layout, Frame &out );

/// Распаковка массива в коды по формату:
///   `Avg`, `Normal` — 1 байт, беззнаковый;
///   `AvgHiRes` — 2 байта BIG-ENDIAN, беззнаковые 0…65535;
///   `PeakInterlaced` — 1 байт на выборку, значения поочерёдно минимум и
///      максимум своего полуинтервала, каждое на своей позиции времени
///      (шаг огибающих, если их строить, вдвое крупнее шага выборок);
///   `PeakPaired` — пара байт на выборку, ПЕРВЫЙ минимум, ВТОРОЙ максимум.
/// Все выборки беззнаковые. [СБОРКА]
bool decodeSamples( const QByteArray &raw, SampleFormat f, ChannelData &out );

