/// \brief `RS` — способ оцифровки. Цитата первоисточника дословно:
/// «бит 0: 0 - однократная (realtime) / 1 - стробоскопическая
/// (эквивалентная, RIS); бит 1: 0 - передача после оцифровки /
/// 1 - параллельная (realtime) передача; бит 2: 0 - буферная
/// (синхронизируемая) оцифровка / 1 - бесконечная (roll) оцифровка».
/// [СБОРКА]
struct AcquisitionMode {
    bool ris = false;      ///< бит 0
    bool parallel = false; ///< бит 1
    bool roll = false;     ///< бит 2

    /// Бесконечная лента: прибор гонит данные сам до пакета Abort.
    ///
    /// **Признак — бит 2, и только он.** Никакого противоречия в
    /// первоисточнике здесь нет, и прежняя редакция этого комментария,
    /// объявлявшая противоречие, была ошибкой чтения — дважды подряд.
    ///
    /// Откуда оно взялось, объяснил автор 2026-09-06: **открытый клиент
    /// реализует только ОДИН режим**, а у windows-приложения вендора
    /// работают все три (исходников его нет). Неполноту клиента я принял за
    /// противоречие документа. Отсюда общее правило для этого прибора:
    /// **отсутствие режима в открытом клиенте — не свидетельство отсутствия
    /// его в приборе.** Клиент годен как источник о ПРОВОДНОМ ФОРМАТЕ и
    /// негоден как источник о том, что прибор умеет.
    ///
    /// Разъяснение автора 2026-09-06: «противоречия нет это 3 разных режима
    /// работы прибора. явный выбор в GUI». Так оно и закодировано в рабочем
    /// клиенте (`ProcessingTypeMode.java`): `RS` — это ТРИ НЕЗАВИСИМЫХ
    /// ПЕРЕКЛЮЧАТЕЛЯ, каждый на своём бите, и каждый ставится отдельно
    /// (`set(0,…)`, `set(1,…)`, `set(2,…)`):
    ///
    ///   бит 0  `ProcessingType`  REALTIME ↔ RIS (стробоскопическая)
    ///   бит 1  `DataOutputType`  POST_PROCESSING ↔ REALTIME (параллельная)
    ///   бит 2  `BufferType`      SYNC ↔ ROLL (бесконечная)
    ///
    /// А таблица режимов в описании протокола — перечень СОЧЕТАНИЙ, которые
    /// имеет смысл выбирать, а не определение битов. Читать её как
    /// определение и значило принять перечень примеров за закон; отсюда и
    /// взялось мнимое противоречие.
    bool isRoll() const { return roll; }

    /// Стробоскопическая (эквивалентная) выборка — для периодики высокой
    /// частоты. Переключатель отдельный: с лентой не связан ничем.
    bool isRis() const { return ris; }

    /// Передача параллельно оцифровке. Тоже отдельный переключатель, но
    /// ленте он нужен по существу: у бесконечного массива нет момента
    /// «оцифровка закончилась», после которого пошли бы данные.
    bool isParallel() const { return parallel; }
};

uint8_t encode( const AcquisitionMode &m );
AcquisitionMode decodeRs( uint8_t rs );

/// \brief `RT` — тип запуска. Цитата: «------00 – автоматический запуск
/// (после TA); ------01 – ждущий запуск (лимит TW); ------10 – свободный
/// запуск; ------11 – бесконечно ждущий запуск». Свободный и бесконечно
/// ждущий поддержаны начиная с версии прошивки 1.25 — на старой прошивке
/// прибор ответит отказом, и это не ошибка клиента. [СБОРКА]
enum class TriggerStart : uint8_t {
    Auto = 0b00,        ///< ждать TA, потом оцифровать без синхронизации
    WaitTimeout = 0b01, ///< ждать TW, потом вернуть ПУСТОЙ кадр
    Free = 0b10,
    WaitForever = 0b11,
};

uint8_t encode( TriggerStart t );
TriggerStart decodeRt( uint8_t rt );

/// \brief `O1` — аппаратный режим канала. Цитата: «Бит0: 0 – канал
/// включен / 1 – вход заземлен; Бит1: 0 – открытый вход (AC+DC) /
/// 1 – закрытый вход (AC); Бит2: 0 – нет фильтрации 3МГц / 1 – включен
/// фильтр 3МГц; Бит3: 0 – нет фильтрации 3кГц / 1 – включен фильтр 3кГц
/// (до 200мВ/дел)». [СБОРКА]
///
/// ВНИМАНИЕ НА БИТ 0: он означает «вход заземлён», а не «канал включён».
/// Эталонная реализация пишет его правильно (инверсией), а читает как
/// есть — и сообщает «канал включён» ровно тогда, когда он заземлён.
/// Здесь поле названо по смыслу бита, а не по смыслу пожелания.
struct ChannelHwMode {
    bool grounded = false;    ///< бит 0: вход заземлён
    bool acCoupling = false;  ///< бит 1: закрытый вход (AC)
    bool filter3MHz = false;  ///< бит 2
    bool filter3kHz = false;  ///< бит 3: применим до 200 мВ/дел
};

uint8_t encode( const ChannelHwMode &m );
ChannelHwMode decodeO1( uint8_t o1 );

/// \brief `T1` — участие канала в синхронизации. Цитата: «Бит4: 0/1 –
/// выключена/включена синхронизация от спада; Бит5: 0/1 –
/// выключена/включена синхронизация от фронта; Биты 1 0: 00/11 –
/// гистерезис порога спада выключен/включен; Биты 3 2: 00/11 –
/// гистерезис порога фронта выключен/включен; Биты 7 6: 00 – ВЧ и НЧ
/// синхронизация / 11 – НЧ синхронизация». [СБОРКА]
///
/// Гистерезисы и полоса задаются ПАРОЙ бит: одиночный бит пары — не
/// «наполовину включено», а неопределённое состояние. Кодирование пишет
/// обе, декодирование читает младшую бита пары.
/// Типовое значение — фронт с гистерезисом фронта, `0x2C`.
struct ChannelSyncMode {
    bool onFall = false;          ///< бит 4
    bool onRise = false;          ///< бит 5
    bool fallHysteresis = false;  ///< биты 1,0 парой
    bool riseHysteresis = false;  ///< биты 3,2 парой
    bool lowFrequencyOnly = false;///< биты 7,6 парой: 11 — только НЧ
};

uint8_t encode( const ChannelSyncMode &m );
ChannelSyncMode decodeT1( uint8_t t1 );

/// Типовая синхронизация: фронт с гистерезисом фронта = 0x2C. Обе
/// эталонные реализации ставят именно её. [СБОРКА]
constexpr uint8_t T1_RISE_WITH_HYSTERESIS = 0x2C;

/// \brief `M1` и формат выборок в кадре — одна и та же раскладка бит 2-0.
///
/// Цитата первоисточника (описание регистра M1): «000 – усреднение с
/// отбрасыванием младших разрядов (1 байт/выборка); 001 – усреднение с
/// повышением разрешения (2 байта/выборка); 010 – пиковый режим –
/// поочередно (2 байта/2 выборки); 011 – пиковый режим – повыборочно
/// (2 байта/выборка); 100 – обычный режим: байт массива = выборка АЦП
/// (1 байт/выборка)».
///
/// В разделе про АТРИБУТЫ КАДРА тот же первоисточник печатает код «100»
/// ДВАЖДЫ — первая строка там должна читаться как «000». Дефект лежит в
/// самом вендорском документе, а не в конспекте; разрешается описанием
/// регистра `M1` в том же документе и совпадающим с ним перечислением
/// эталонного кода. Здесь принята непротиворечивая раскладка. [СБОРКА]
enum class SampleFormat : uint8_t {
    Avg = 0b000,            ///< усреднение с отбрасыванием младших разрядов
    AvgHiRes = 0b001,       ///< усреднение с повышением разрешения
    PeakInterlaced = 0b010, ///< пиковый поочерёдно: 2 байта на 2 выборки
    PeakPaired = 0b011,     ///< пиковый повыборочно: пара min,max на выборку
    Normal = 0b100,         ///< байт массива = выборка АЦП
};

/// Разбор трёх младших бит с ОБЯЗАТЕЛЬНОЙ маской `& 0x07`. Без маски
/// любой установленный резервный бит уводит распознавание в `Normal`
/// молча — именно это делает эталонная реализация на Java. false —
/// комбинация бит не объявлена ни одним форматом. [СБОРКА]
bool decodeSampleFormat( uint8_t raw, SampleFormat &out );
uint8_t encode( SampleFormat f );
const char *sampleFormatName( SampleFormat f );

/// Сколько БАЙТ массива приходится на одну выборку: 2 у `AvgHiRes` и
/// `PeakPaired`, 1 у остальных. У `PeakInterlaced` байт один: пара
/// «2 байта / 2 выборки» означает, что минимум и максимум занимают
/// СВОИ соседние позиции на оси времени, а не одну общую. [СБОРКА]
int sampleBytes( SampleFormat f );

/// Ширина одного читаемого целого: 2 только у `AvgHiRes`. У
/// `PeakPaired` поток читается побайтно, но на выборку приходится два
/// байтовых элемента — величины разные, и путать их нельзя. [СБОРКА]
int sampleWordBytes( SampleFormat f );

/// Число выборок в массиве такого размера.
int samplesInBytes( SampleFormat f, int sizeBytes );

/// Полная шкала кода при этом формате: 0xFFFF у `AvgHiRes`, иначе 0xFF.
int codeFullScale( SampleFormat f );

