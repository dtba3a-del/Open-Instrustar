/// Единица регистров `MC`, `MCd`, `MCl`, `D1m` — 10 пикосекунд. [СБОРКА]
constexpr double TICK_UNIT_PS = 10.0;
/// Единица задержек `TD`, `TA`, `TW` — 12 машинных тактов. [СБОРКА]
constexpr int DELAY_UNIT_TICKS = 12;
/// Период выборки `TS` задан в тактах, умноженных на 256. [СБОРКА]
constexpr int TS_TICK_SCALE = 256;
/// Делений по вертикали, на которые прибор растягивает свою шкалу.
/// Здесь это ПАРАМЕТР ПО УМОЛЧАНИЮ, а не второй источник числа делений
/// представления CtPU: вызывающий обязан передать своё, если работает в
/// другом представлении. [СБОРКА]
constexpr int DEFAULT_DIVS_VOLTAGE = 8;
/// Максимум `MC`, объявленный эталонной реализацией: 65500 = 655 нс. [СБОРКА]
constexpr uint16_t MC_MAX = 65500;

/// Длительность машинного такта, пс.
double tickPs( uint16_t mc );
/// Такт из желаемой длительности и из частоты. `MC = round(1e5 / f[МГц])`
/// — та же формула, что в эталонном коде. Частота здесь — тактовая
/// частота контроллера в MHz, не скорость выборки. [СБОРКА]
uint16_t mcFromTickPs( double ps );
uint16_t mcFromMHz( double megahertz );

/// Период выборки: `T_s[пс] = TS × (MC × 10) / 256`. Совпадает в обеих
/// эталонных реализациях. [СБОРКА]
double samplePeriodPs( uint32_t ts, uint16_t mc );
uint32_t tsFromSamplePeriodPs( double ps, uint16_t mc );

/// Скорость выборки в Sps — обратная периоду. Ноль периода даёт ноль:
/// «бесконечно быстро» не бывает, а деления на ноль здесь нет. [СБОРКА]
double sampleRateSps( uint32_t ts, uint16_t mc );

/// Время на деление при заданном числе выборок на деление. Число выборок
/// на деление — величина ПРЕДСТАВЛЕНИЯ, а не прибора: эталонные
/// реализации взяли разное (32 у одной, до 100 у другой), поэтому здесь
/// оно аргумент без значения по умолчанию. [СБОРКА]
double timePerDivPs( uint32_t ts, uint16_t mc, int samplesPerDiv );

/// Задержки `TD`/`TA`/`TW`: `t = N × 12 × такт`. **Единица объявлена
/// первоисточником, но ни одна эталонная реализация её не применяет —
/// обе пишут сырые числа.** Формула выведена из единицы измерения и
/// кодом не подтверждена; ошибка здесь даст неверное ожидание
/// синхронизации, а не сбой связи. [СБОРКА]
double delayPs( uint32_t units, uint16_t mc );
uint32_t delayUnitsFromPs( double ps, uint16_t mc );

/// Чувствительность: значение регистра `V1` равно числу милливольт на
/// деление напрямую (`V1 = 200` ↔ 200 мВ/дел; `V1l = 20` ↔ 20 мВ/дел;
/// `V1h = 10000` ↔ 10 В/дел). [СБОРКА]
double milliVoltsPerDiv( uint16_t v1 );
uint16_t v1FromMilliVoltsPerDiv( double mvPerDiv );

/// \brief Сколько кодов АЦП укладывается в экран.
///
/// **УСТАНОВЛЕНО 2026-09-06 по спецификации изготовителя: 256 кодов на
/// 8 делений, то есть 32 кода на деление.** Прежде здесь стоял отказ считать:
/// описание протокола давало единицу `V1` двумя несводимыми числами — «8 мВ
/// на диапазон АЦП» в разделе свойств и «8,53 мВ» в разделе регистров, а
/// 8,53/8 = 256/240, то есть числа отвечали двум разным рамкам (240 кодов на
/// экране с запасом на выбросы против всех 256).
///
/// Спор решён таблицей аттенюатора с сайта изготовителя
/// (`references/vendor/oscill/site/155-attdata.html`), и решён нацело:
/// девять строк из девяти сходятся с делением на 256 и ни одна — на 240.
///
/// ```
///   В/дел     амплитуда   делений   ампл/256   ампл/240   у вендора
///    20 мВ      160 мВ        8       0,625      0,667       0,6
///   100 мВ      800 мВ        8       3,125      3,333       3,1
///     1 В         8 В         8      31,250     33,333        31
///    10 В        80 В         8     312,500    333,333       310
/// ```
///
/// Отсюда сразу три следствия, и каждое сверено с той же спецификацией:
///   * полная шкала = **8 делений**, `V1` = милливольты на деление
///     (`V1l = 0x0014` = 20 мВ/дел, `V1h = 0x2710` = 10 В/дел — ровно ряд
///     «20 мВ..10 В/дел» с главной страницы сайта);
///   * шаг смещения `P1` = 1/256 диапазона = 1/32 деления; предел
///     `P1h = 0x0180` = 384 даёт 384/256 × 8 = **±12 делений**, и столько же
///     заявлено в характеристиках канала («смещение по вертикали, делений
///     шкалы, не менее — ±12, кроме 10В/дел; ±8 только для 10В/дел»);
///   * уровень запуска `S1` — 8 бит на те же 8 делений, то есть дискретность
///     **1/32 деления**, и ровно это стоит в характеристиках запуска.
///
/// Три независимых величины, посчитанные из одной рамки, сошлись с тремя
/// независимыми строками спецификации. `Unverified` сохранён: он нужен, когда
/// прибор отвечает не так, как написано в его же документации.
enum class CodeSpan : int {
    Unverified = 0, ///< не установлено на приборе: пересчёт запрещён
    Codes240 = 240, ///< экран = 240 кодов, 16 кодов запаса сверху и снизу
    Codes256 = 256, ///< экран = весь диапазон АЦП
};

/// Смещение окна АЦП в милливольтах. Единица `P1` — «1/256 диапазона
/// АЦП», то есть один код; в милливольтах шаг кода зависит от того,
/// сколько кодов приходится на экран, — отсюда `CodeSpan` и здесь.
/// При `Codes256` выражение сводится ровно к `(V1 × 8 / 256) × P1`,
/// которое считают обе эталонные реализации. false — рамка не
/// установлена. [СБОРКА]
bool offsetMillivolts( int16_t p1, uint16_t v1, CodeSpan span, double &outMv,
                       int divs = DEFAULT_DIVS_VOLTAGE );
/// Обратно: сколько кодов смещения даёт желаемый сдвиг в милливольтах.
bool p1FromOffsetMillivolts( double mv, uint16_t v1, CodeSpan span, int16_t &outP1,
                             int divs = DEFAULT_DIVS_VOLTAGE );

/// Уровень синхронизации `S1`: `уровень = vMin + ((vMax − vMin)/256) × S1`,
/// где `vMax = +V1×divs/2`, `vMin = −V1×divs/2`. `S1 = 128` — центр
/// экрана. Обратная функция ОБЯЗАНА вычитать `vMin`: эталонная
/// реализация этого не делает, и её круговой пересчёт не сходится —
/// 0 мВ даёт `S1 = 0` вместо 128. [СБОРКА]
double triggerLevelMv( uint8_t s1, uint16_t v1, int divs = DEFAULT_DIVS_VOLTAGE );
uint8_t s1FromTriggerLevelMv( double mv, uint16_t v1, int divs = DEFAULT_DIVS_VOLTAGE );

/// Конструктивная задержка компаратора синхронизации, пс: `D1m × 10`.
/// Свойство зависит от `S1` и `T1` — перечитывать после их записи. [СБОРКА]
double comparatorDelayPs( uint16_t d1m );

/// Шкала канала: границы окна и шаг кода. Величина без установленной
/// рамки (`CodeSpan::Unverified`) непригодна — поэтому `known`, а не
/// «ну возьмём 256».
struct ChannelScale {
    bool known = false;
    double minMv = 0; ///< нижняя граница окна с учётом смещения
    double maxMv = 0; ///< верхняя граница окна
    double stepMv = 0;///< милливольт на один код текущего формата
};

/// Шкала при заданных чувствительности, смещении, формате и рамке.
/// Формат нужен потому, что `AvgHiRes` кладёт на тот же размах 65536
/// кодов вместо 256. [СБОРКА]
ChannelScale channelScale( uint16_t v1, int16_t p1, SampleFormat fmt, CodeSpan span,
                           int divs = DEFAULT_DIVS_VOLTAGE );

/// Код → милливольты: `V = vMin + code × stepMv`. false — шкала не
/// установлена; числа на выходе в этом случае нет вовсе. [СБОРКА]
bool codeToMillivolts( int code, const ChannelScale &scale, double &outMv );

/// Ось времени кадра: `t[i] = T_s × i − TC × T_s`. Момент синхронизации
/// приходится на `t = 0`; `TC` — центровка в выборках. [СБОРКА]
double sampleTimePs( int index, double samplePeriodPsValue, uint16_t tc );

