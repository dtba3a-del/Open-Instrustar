/// \brief Значение прибора вместе с признаком «прочитано ли оно вообще».
///
/// Ноль «не прочитано» неотличим от нуля-значения, а на этих числах
/// строятся деления (период выборки, шаг напряжения) и границы
/// (`QSh`, `V1h`, `TDl`). Прибор вправе ответить `0xD1 Not Implemented`
/// на любое свойство — тогда величины НЕТ, и это состояние, а не ошибка
/// связи. Поэтому признак вынесен в тип, а не в комментарий: величина
/// без происхождения в конвейер не идёт.
template < class T > struct Known {
    T value = T();
    bool known = false;

    Known() = default;
    Known( T v, bool k ) : value( v ), known( k ) {}

    /// Значение или названная замена. Замена ОБЯЗАНА быть названа в
    /// точке вызова: молчаливого «ну ноль» здесь нет.
    T orElse( T fallback ) const { return known ? value : fallback; }
    void set( T v ) {
        value = v;
        known = true;
    }
    void forget() {
        value = T();
        known = false;
    }
};

