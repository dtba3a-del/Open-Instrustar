/// \file oscillprotocol.h
/// \brief Знание о приборе Oscill: имена, разряды, побитовые раскладки,
///        пересчёты в физические единицы и разбор кадра. Ввода-вывода нет.
///
/// ЗАЧЕМ ОТДЕЛЬНО ОТ БЭКЕНДА
///
/// Всё, что здесь объявлено, есть чистая функция байтов и чисел: имя
/// регистра, его ширина, значение бита, формула пересчёта, разбор тела
/// кадра. Ничего из этого не требует прибора, а значит проверяется
/// тестами полностью. Бэкенд, наоборот, требует порта и сессии — и
/// проверяется только частично. Смешение этих двух сущностей означало бы,
/// что формулу пересчёта нельзя проверить, не подняв сессию.
///
/// СТЕК. Oscill (OBEX поверх последовательного порта) не имеет ни одного
/// общего факта ни с путём A (`vdso.dll`), ни с путём B (fx2lafw+libusb)
/// осциллографа ISDS205. Перенос числа между стеками — самая дорогая
/// ошибка проекта (`docs/ACCESS_PATHS.md`); здесь она предотвращена тем,
/// что ни одна константа этого файла не берётся из тех стеков.
///
/// ЕДИНИЦЫ. Скорость выборки — Sps/kSps/MSps, частота сигнала — Hz/kHz/MHz;
/// внутренние величины прибора — в его собственных единицах (машинный
/// такт 10 пс, период выборки в тактах×256, задержки в 12 тактах,
/// чувствительность в мВ/дел). Пересчёт делается ЗДЕСЬ и только здесь:
/// у величины одно место, которое её порождает (`docs/ДВОЕВЛАСТИЕ.md`).
///
/// СОСТОЯНИЕ УТВЕРЖДЕНИЙ. Прибора в работе нет: всё ниже — **[СБОРКА]**,
/// то есть выведено из первоисточника и двух эталонных реализаций и
/// проверяется тестами, но не измерено на приборе. Там, где источники
/// расходятся между собой и бумага вопрос не закрывает, выбор НЕ делается
/// молча: он вынесен в тип (`CodeSpan`, `FrameLayout`, `WriteStyle`),
/// и до измерения на приборе соответствующий пересчёт отказывает вслух.

