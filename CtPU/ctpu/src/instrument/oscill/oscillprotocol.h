/// \brief Каким пакетом писать регистр. **На приборе не проверено.**
///
/// Первоисточник документирует обе формы: запись пакетом PUT и
/// СОВМЕЩЁННУЮ запись-с-чтением одним пакетом GET («самый эффективный
/// способ работы регистром, который нужно изменить»). Эталонные
/// реализации разошлись: одна пишет GET, другая PUT. Выбор оставлен
/// вызывающему и виден в подписи — значения по умолчанию нет намеренно,
/// иначе «выбранное молча» через полгода станет «проверенным». [СБОРКА]
enum class WriteStyle {
    CombinedGet, ///< 0x83: имя + значение в одном GET, ответ несёт факт
    PutFinal,    ///< 0x82: имя + значение в PUT; факт читать отдельным GET
};

/// GET `0x70` + имя свойства. Ответ несёт имя и значение. [СБОРКА]
QByteArray makeReadProperty( Property p, bool withChecksum );
/// GET `0x71` + имя регистра. [СБОРКА]
QByteArray makeReadRegister( Register r, bool withChecksum );
/// Запись регистра выбранной формой. Ширина заголовка значения берётся
/// из `registerDef()`, знаковое значение упаковывается дополнительным
/// кодом нужной ширины. [СБОРКА]
QByteArray makeWriteRegister( Register r, uint32_t value, WriteStyle style, bool withChecksum );
/// Команда: `0x72` + один символ. Оцифровка `'D'` — пакетом GET,
/// калибровка `'C'` — пакетом PUT, загрузка фрагмента прошивки `'F'`
/// здесь не поддержана намеренно (прошивку этот бэкенд не трогает). [СБОРКА]
QByteArray makeCommand( char cmd, bool asPut, bool withChecksum );
inline QByteArray makeDigitize( bool withChecksum ) { return makeCommand( 'D', false, withChecksum ); }
inline QByteArray makeCalibrate( bool withChecksum ) { return makeCommand( 'C', true, withChecksum ); }

/// Значение регистра из ответа: ищет заголовок значения (`0xB1`/`0xF0`/
/// `0xF1`) и приводит по ширине регистра. false — ответ значения не
/// нёс (в том числе `0xD1 Not Implemented`), и это НЕ ноль. [СБОРКА]
bool valueFromResponse( const Response &r, Register reg, uint32_t &out );
/// То же для свойства; для ASCII-свойств отдаёт текст без нулей.
bool valueFromResponse( const Response &r, Property prop, uint32_t &out );
bool asciiFromResponse( const Response &r, QByteArray &out );

