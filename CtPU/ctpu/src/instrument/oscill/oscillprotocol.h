/// Регистр прибора. Порядок перечисления — порядок ПРИОРИТЕТА, в котором
/// их полагается записывать: `TS` ни от чего не зависит и стоит выше
/// всех, `QS`/`TC` зависят почти от всего и ставятся последними
/// (см. `initOrder()` — там порядок записи, а не приоритета). [СБОРКА]
enum class Register : int {
    MC, ///< 2 б; машинный такт, ед. 10 пс; максимум 655 нс (≈1,5 МГц)
    TS, ///< 4 б; период выборки, ед. такты×256; наивысший приоритет
    RS, ///< 1 б побитно; способ оцифровки (см. AcquisitionMode)
    AP, ///< 1 б; число проходов усреднения/пика минус 1 (степень двойки, до 256)
    AR, ///< 1 б; минимум оцифровок с одинаковой задержкой в RIS
    QS, ///< 2 б; размер выходного массива, ед. «выборка», максимум — QSh
    TC, ///< 2 б; центровка развёртки, ед. «выборка», 0…QS
    TD, ///< 4 б; задержка развёртки, ед. 12 тактов, границы TDl…TDh
    RT, ///< 1 б побитно; тип запуска (см. TriggerStart)
    TA, ///< 4 б; предел ожидания синхронизации при автозапуске, ед. 12 тактов
    TW, ///< 4 б; предел ожидания при ждущем запуске, ед. 12 тактов
    O1, ///< 1 б побитно; аппаратный режим канала (см. ChannelHwMode)
    V1, ///< 2 б; чувствительность канала, мВ/дел
    P1, ///< 2 б ЗНАКОВЫЙ; смещение окна АЦП, ед. 1/256 диапазона АЦП
    M1, ///< 1 б побитно; обработка выборок в приборе (см. SampleFormat)
    T1, ///< 1 б побитно; участие канала в синхронизации (см. ChannelSyncMode)
    S1, ///< 1 б БЕЗЗНАКОВЫЙ; уровень синхронизации, 0…255 от диапазона АЦП
};

struct RegisterDef {
    const char *name; ///< ровно 2 символа ASCII
    uint8_t width;    ///< 1, 2 или 4 байта
    bool isSigned;    ///< только P1
    const char *unit;
};

const RegisterDef &registerDef( Register r );
inline const char *registerName( Register r ) { return registerDef( r ).name; }
const std::vector< Register > &allRegisters();

