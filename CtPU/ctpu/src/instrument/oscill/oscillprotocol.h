/// Что нужно, чтобы посчитать защитный интервал ожидания ответа на `'D'`.
struct CaptureTiming {
    uint16_t mc = 0;
    uint32_t ts = 0;
    uint16_t qs = 0;
    TriggerStart rt = TriggerStart::Auto;
    uint32_t ta = 0;
    uint32_t tw = 0;
    uint32_t td = 0;
};

/// \brief Защитный интервал: сколько прибор вправе молчать после `'D'`.
///
/// Не таймаут «на всякий случай», а вычисленная величина: ожидание
/// синхронизации (`TA` при автозапуске, `TW` при ждущем) плюс задержка
/// развёртки `TD` плюс собственно оцифровка `TS × QS`. Правило
/// первоисточника: **появление даже одного байта есть ответ** (пусть
/// ошибочный) и ведёт к перезапросу `0x92`; повтор запроса делается
/// только при ПОЛНОМ отсутствии байт и только по истечении этого
/// интервала. При `WaitForever` величины нет — ждать позволено сколько
/// угодно, и функция вернёт бесконечность. [СБОРКА]
double captureWindowPs( const CaptureTiming &t );

/// Порядок записи регистров при настройке прибора. Взят из рабочего
/// эталонного кода: `MC → RS → TD → TA → TW → AR → AP → O1 → M1 → V1 →
/// P1 → T1 → S1 → RT → QS → TS → TC`. `QS`/`TS`/`TC` стоят ПОСЛЕДНИМИ —
/// в эталонном коде на этом месте стоит пометка «set last». После всего
/// полагается калибровка `'C'`, а после неё перечитываются `P1` и `S1`:
/// калибровка привязывает смещение канала и уровень синхронизации к
/// диапазону АЦП. [СБОРКА]
const std::vector< Register > &initOrder();

/// \brief Что перечитать после записи этого регистра (П3).
///
/// Граф собран по описаниям первоисточника, а НЕ по эталонному коду: в
/// коде связи `RS → {TD, M1}` и `TS → {RS, M1, TD}` не заведены вовсе,
/// хотя документация их требует, и после записи `RS`/`TS` зависимые
/// регистры там не перечитываются. Здесь они есть. [СБОРКА]
std::vector< Register > dependentRegisters( Register r );
/// Свойства, границы которых сдвигаются после записи этого регистра:
/// `V1 → {P1h, P1l}`, `RS/TS/M1/AP → {QSh, TCh}`, `RS/TS/QS → {TDl, TDh}`,
/// `S1/T1 → {D1m}`. [СБОРКА]
std::vector< Property > dependentProperties( Register r );

