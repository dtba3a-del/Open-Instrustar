/// \brief Свойства, прочитанные один раз при `link()`.
///
/// Один раз — потому что свойства не меняются сами: они суть описание
/// того, что прибор умеет. Часть из них сдвигается как следствие записи
/// регистров (границы `QSh`, `TCh`, `TDl`/`TDh`, `P1h`/`P1l`) и
/// перечитывается по правилу П3 — но не в горячем цикле.
///
/// Каждое поле помечено признаком «прочитано ли»: прибор вправе ответить
/// `0xD1 Not Implemented` на любое свойство, и тогда величины НЕТ.
/// Отличить это от нуля обязан тип, а не примечание: на `QSh` и `V1h`
/// строятся границы, на такте — деления.
struct OscillPassport {
    bool valid = false; ///< паспорт прочитан хотя бы в обязательной части

    // Опознание. Оба списка версий из первоисточников: какой поддержан
    // прибором — показывает опрос, а не выбор на бумаге.
    QString deviceId;   ///< VNM
    QString serial;     ///< VSN
    QString hardware;   ///< VHW либо VHD/VHA, если прибор отвечает ими
    QString software;   ///< VSW либо VSD/VSI/VSC/VSO

    // Времязадающая часть
    Oscill::Known< uint16_t > tickDefault; ///< MCd, ед. 10 пс
    Oscill::Known< uint16_t > tickMin;     ///< MCl, ед. 10 пс («разгон»)
    Oscill::Known< uint16_t > tsRealtimeMin; ///< TOl, такты×256
    Oscill::Known< uint32_t > fastVariants;  ///< TOv, битовая карта
    Oscill::Known< uint16_t > tsRisMin;      ///< TMl
    Oscill::Known< uint16_t > tsRisMax;      ///< TMh
    Oscill::Known< uint32_t > tsParallelMin; ///< TPl
    Oscill::Known< uint16_t > preSamplesMax; ///< TCh, ед. «выборка»
    Oscill::Known< uint16_t > samplesMax;    ///< QSh, ед. «выборка»
    Oscill::Known< uint32_t > delayMin;      ///< TDl, ед. 12 тактов
    Oscill::Known< uint32_t > delayMax;      ///< TDh, ед. 12 тактов

    // Канал
    Oscill::Known< uint16_t > sensitivityCoarse; ///< V1h, мВ/дел (низшая чувствительность)
    Oscill::Known< uint16_t > sensitivityFine;   ///< V1l, мВ/дел (наивысшая)
    Oscill::Known< int16_t > offsetMax;          ///< P1h, ед. 1/256 диапазона АЦП
    Oscill::Known< int16_t > offsetMin;          ///< P1l
    Oscill::Known< uint16_t > comparatorDelay;   ///< D1m, ед. 10 пс

    /// Границы чувствительности как ИНТЕРВАЛ, а не как пара «нижняя,
    /// верхняя» в порядке имён. Имена обманывают: `V1h` — это 10 В/дел,
    /// то есть БОЛЬШЕЕ число и НИЗШАЯ чувствительность. Эталонная
    /// реализация построила интервал прямо по именам, получила
    /// `[10000; 20]` и её общий отсекатель поднимает любую
    /// чувствительность до 10 В/дел. Здесь порядок восстанавливается
    /// явно. [СБОРКА]
    bool sensitivityRange( uint16_t &minMvPerDiv, uint16_t &maxMvPerDiv ) const;
};

// ===========================================================================
// Настройки
// ===========================================================================

/// \brief Настройки прибора в его собственных единицах — сырые значения
/// регистров.
///
/// Именно сырые: пересчёт в вольты, секунды и Sps живёт в
/// `oscillprotocol.h` и только там. Держать здесь ещё и «В/дел» значило
/// бы завести у величины второе место, которое её порождает, — и рано
/// или поздно эти два места разойдутся.
struct OscillSettings {
    uint16_t mc = 0;  ///< машинный такт, ед. 10 пс
    uint32_t ts = 0;  ///< период выборки, такты×256
    uint8_t rs = 0;   ///< способ оцифровки (Oscill::decodeRs)
    uint8_t ap = 0;   ///< проходов усреднения минус 1
    uint8_t ar = 0;   ///< минимум оцифровок с одинаковой задержкой в RIS
    uint16_t qs = 0;  ///< размер массива, ед. «выборка»
    uint16_t tc = 0;  ///< центровка развёртки, ед. «выборка»
    uint32_t td = 0;  ///< задержка развёртки, ед. 12 тактов
    uint8_t rt = 0;   ///< тип запуска (Oscill::decodeRt)
    uint32_t ta = 0;  ///< предел ожидания автозапуска, ед. 12 тактов
    uint32_t tw = 0;  ///< предел ожидания ждущего запуска, ед. 12 тактов
    uint8_t o1 = 0;   ///< аппаратный режим канала (Oscill::decodeO1)
    uint16_t v1 = 0;  ///< чувствительность, мВ/дел
    int16_t p1 = 0;   ///< смещение окна АЦП, ед. 1/256 диапазона АЦП
    uint8_t m1 = 0;   ///< формат выборок (Oscill::decodeSampleFormat)
    uint8_t t1 = 0;   ///< синхронизация канала (Oscill::decodeT1)
    uint8_t s1 = 0;   ///< уровень синхронизации, 0…255
};

/// Регистр, факт которого разошёлся с запрошенным. Не ошибка: прибор
/// вправе подрезать. Ошибкой было бы промолчать.
struct RegisterMismatch {
    Oscill::Register reg = Oscill::Register::MC;
    uint32_t wanted = 0;
    uint32_t actual = 0;
};

