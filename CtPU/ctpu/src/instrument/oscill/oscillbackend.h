/// \brief Oscill: одноканальный изолированный осциллограф на OBEX.
class OscillBackend final : public Backend, public WaveformSource {
  public:
    /// Ход сессии. Нужен наружу потому, что `update()` делает ОДИН
    /// неблокирующий шаг: тот, кто его зовёт, вправе знать, чего ждут.
    enum class Step {
        Offline,     ///< связи нет
        Idle,        ///< связь есть, оцифровка не запрошена
        Requested,   ///< команда 'D' отдана, первого байта ответа нет
        Assembling,  ///< ответ идёт, части 0x48 накапливаются
        Rolling,     ///< бесконечная лента; прибор говорит сам, опрос не нужен
        Recovering,  ///< перезапрос 0x92 или повтор запроса после интервала
    };

    /// Счётчики линии (П8). Не украшение: перезапросы и молчание — это
    /// то, по чему видно, что связь на грани, ЗАДОЛГО до её обрыва.
    struct LinkStats {
        unsigned repeatsSent = 0;      ///< отправлено 0x92
        unsigned badChecksum = 0;      ///< сумма не сошлась
        unsigned lengthMismatch = 0;   ///< факт длины ≠ объявленной
        unsigned serverErrors = 0;     ///< 0xD0 от прибора
        unsigned notImplemented = 0;   ///< 0xD1: свойства/регистра нет
        unsigned silentIntervals = 0;  ///< молчание дольше защитного интервала
        unsigned framesReceived = 0;
        unsigned framesEmpty = 0;      ///< П2: пустой 0x49 по истечении TW
        unsigned framesUnsynchronized = 0; ///< П2: запуск по таймауту
    };

    explicit OscillBackend( TransportPtr transport );
    ~OscillBackend() override;

    // --- Instrument::Backend ---

    /// Есть ли порт на назначенном месте. Порт НЕ открывается и пакетов
    /// не шлётся: `probe()` ничего в приборе не меняет, а открытие
    /// чужого COM-порта — уже вмешательство. Отвечает
    /// `SerialTransport::exists()`. [СБОРКА]
    bool probe() override;

    /// Сброс `Abort` → пауза → вычистка буфера → CONNECT → чтение
    /// паспорта. Именно в этом порядке: обе эталонные реализации перед
    /// CONNECT шлют `FF 00 03` и ждут, иначе прибор досказывает хвост
    /// прошлой сессии. После успеха `state().linked == true`,
    /// `state().model`, `.firmware`, `.transport` заполнены. [СБОРКА]
    bool link() override;

    /// `Abort` (если шла лента), `Disconnect`, закрытие порта. Безопасен
    /// без связи и при повторе: `setTransport()` зовёт его безусловно.
    void unlink() override;

    /// ОДИН неблокирующий шаг: отдать `'D'`, забрать то, что пришло,
    /// разобрать готовое. Ни одной паузы «на всякий случай» — ожидание
    /// меряется защитным интервалом `Oscill::captureWindowPs()`,
    /// вычисленным из регистров. В `Step::Rolling` не делает ничего:
    /// ленту прибор гонит сам.
    void update() override;

    /// Паспорт потока. `pace` вычисляется из текущего `RS`:
    /// `Pace::Stream` в бесконечной оцифровке, иначе `Pace::OnRequest`.
    /// `bytesPerPortion = QS × байт на выборку по M1`;
    /// `decimatedAtSource = true` — прореживание делает сам прибор
    /// (усреднение и пиковый режим до 256 проходов внутри него).
    Flow flow() const override;

    Type type() const override; ///< Type::Oscill

    // --- Instrument::WaveformSource ---

    /// Ровно 1. Канал у Oscill один — это свойство прибора, а не
    /// текущей настройки. Число каналов в атрибутах кадра (биты 7-6)
    /// разбирается всё равно: формат кадра рассчитан на четыре, и
    /// молчаливое предположение «там всегда один» уже стоило эталонной
    /// реализации неверного разбора. [СБОРКА]
    unsigned channelCount() const override;

    /// Скорость выборки, Sps: обратная периоду `TS` при такте `MC`.
    /// Ноль означает «период не установлен», а не «ноль отсчётов в
    /// секунду».
    double samplerate() const override;

    // --- Паспорт, настройки, П3 ---

    const OscillPassport &passport() const;

    /// ФАКТИЧЕСКИЕ значения регистров, прочитанные у прибора. Не то, что
    /// просили: см. П3 в шапке файла.
    const OscillSettings &settings() const;

    /// Записать регистр и вернуть факт. `actual` заполняется ВСЕГДА при
    /// возврате true — совмещённой транзакцией или отдельным чтением, в
    /// зависимости от `registerWriteStyle()`. false — отказ линии или
    /// протокола (в том числе `0xD1`: такого регистра нет). [СБОРКА]
    bool writeRegister( Oscill::Register reg, uint32_t wanted, uint32_t &actual );

    bool readRegister( Oscill::Register reg, uint32_t &value );

    /// Свойство как число (двух- и четырёхбайтовые свойства).
    bool readProperty( Oscill::Property prop, uint32_t &value );
    /// Свойство как текст (VNM/VSN/VHW/VSW и версии узлов).
    bool readPropertyAscii( Oscill::Property prop, QString &text );

    /// Записать настройки целиком в порядке `Oscill::initOrder()`:
    /// `QS`/`TS`/`TC` последними. Факты оседают в `settings()`,
    /// расхождения — в `mismatches()`. false — хотя бы одна запись не
    /// прошла по линии; подрезанное прибором значение отказом НЕ
    /// считается. [СБОРКА]
    bool applySettings( const OscillSettings &wanted );

    /// Регистры, чей факт разошёлся с запрошенным при последнем
    /// `applySettings()`/`writeRegister()`. Показывать, а не прятать.
    const std::vector< RegisterMismatch > &mismatches() const;

    /// Перечитать зависимые регистры и свойства после записи `reg`
    /// (граф — в `oscillprotocol.h`). Зовётся автоматически из
    /// `writeRegister()`; открыт наружу для случая, когда состояние
    /// прибора могли сдвинуть иначе — например калибровкой.
    bool refreshDependents( Oscill::Register reg );

    /// Команда `'C'`: прибор масштабирует и привязывает смещение канала
    /// и уровень синхронизации к диапазону АЦП. После неё `P1` и `S1`
    /// ОБЯЗАНЫ быть перечитаны — калибровка их меняет; функция делает
    /// это сама. [СБОРКА]
    bool calibrate();

    // --- Кадр ---

    /// Последний разобранный кадр. `valid == false` — кадра ещё не
    /// было; `empty == true` — П2, ждущий запуск не дождался
    /// синхронизации; `synchronized() == false` при непустом кадре — П2,
    /// запуск по таймауту, данные годны и не синхронизированы.
    const Oscill::Frame &frame() const;

    /// Растёт на каждый НОВЫЙ кадр, включая пустой. По нему показ
    /// отличает «новый кадр» от «тот же самый»; сравнение самих данных
    /// для этого не годится — повторяющийся сигнал даёт одинаковые
    /// массивы.
    unsigned long long frameSerial() const;

    /// Шкала канала для последнего кадра. `known == false` означает, что
    /// рамка `CodeSpan` не установлена на приборе и пересчёт кодов в
    /// милливольты запрещён: величина без единицы и годности числом не
    /// показывается (`docs/СЛЫШИМОСТЬ.md`).
    Oscill::ChannelScale channelScale() const;

    /// Рамка пересчёта кодов в напряжение. По умолчанию
    /// `CodeSpan::Unverified`: противоречие «8 мВ против 8,53 мВ»
    /// разрешается одним измерением на приборе, и до него бэкенд отдаёт
    /// коды, а не вольты. Устанавливается настройкой, а не догадкой. [ПЛАН]
    Oscill::CodeSpan codeSpan() const;
    void setCodeSpan( Oscill::CodeSpan span );

    /// Раскладка кадра — с полем размера массива или без него.
    /// Определяется по первому кадру опытом (`Oscill::detectLayout`),
    /// запоминается и печатается в журнал; принудительная установка
    /// нужна тестам и разбору записей. [СБОРКА]
    Oscill::FrameLayout frameLayout() const;
    void setFrameLayout( Oscill::FrameLayout layout );

    // --- Бесконечная лента (roll) ---

    /// Запустить ленту: `RS` с бесконечной оцифровкой и команда `'D'`.
    /// После успеха `flow().pace == Pace::Stream`, и общий обход этот
    /// слот больше не трогает. [СБОРКА]
    bool startRoll();

    /// Остановить ленту пакетом `Abort` — иначе никак: прибор
    /// прекращает поток ТОЛЬКО по требованию хоста. Перестать читать
    /// недостаточно, порт останется забит недосказанным ответом.
    /// После `Abort` — пауза и вычистка буфера. [СБОРКА]
    bool stopRoll();

    bool rollRunning() const;

    /// Порция ленты, накопленная с прошлого вызова, уже разобранная в
    /// коды. Атрибуты в ленте приходят ОДИН раз, в начале потока, и в
    /// пакетах `Continue` не повторяются — формат порции берётся из
    /// `frame()`. Пусто — новых данных нет. [СБОРКА]
    std::vector< int > takeRollSamples();

    // --- Линия (П8) ---

    /// Согласовать скорость: команда прибору `0x91` с коэффициентом,
    /// затем смена скорости у себя. Порядок именно такой — прибор
    /// переходит на новую скорость после ответа на своей старой. false —
    /// коэффициента для такой скорости нет либо прибор не ответил; в
    /// этом случае скорость линии НЕ меняется, иначе связь потерялась бы
    /// молча. [СБОРКА]
    bool negotiateSpeed( int baud );

    /// Ставить ли контрольную сумму `0xB0` в исходящие пакеты и
    /// проверять ли её во входящих. По первоисточнику сумма
    /// необязательна; ни одна эталонная реализация её не считает вовсе.
    /// Здесь она включаема, потому что перезапрос `0x92` без неё
    /// беспомощен: неверную сумму нечем обнаружить. [СБОРКА]
    bool checksumEnabled() const;
    void setChecksumEnabled( bool on );

    /// Каким пакетом писать регистры. На приборе не проверено, поэтому
    /// это настройка, а не константа (см. `Oscill::WriteStyle`). [СБОРКА]
    Oscill::WriteStyle registerWriteStyle() const;
    void setRegisterWriteStyle( Oscill::WriteStyle style );

    /// Каким опкодом запрашивать продолжение длинного ответа: `0x03` или
    /// `0x83`. Эталонные реализации разошлись, первоисточник формы не
    /// уточняет («клиент забирает следующую порцию запросом Get»). [СБОРКА]
    bool continueWithFinalBit() const;
    void setContinueWithFinalBit( bool on );

    const LinkStats &linkStats() const;
    Step step() const;

    /// Приёмный буфер прибора, объявленный им в ответе на CONNECT.
    /// `known == false` — прибор его не назвал, и режем по
    /// `Oscill::SAFE_TX_LIMIT`. [СБОРКА]
    Oscill::Known< uint16_t > deviceRxBuffer() const;

  private:
    // --- Сессия OBEX ---
    bool sendPacket( const QByteArray &packet );
    /// Прочитать один ответ целиком: длина берётся из объявленной,
    /// молчание меряется защитным интервалом. `ParseError` наружу не
    /// уходит — он превращается в перезапрос или в `lastError`.
    bool receiveResponse( Oscill::Response &out, int guardMs );
    /// Транзакция «запрос → ответ» с политикой П8: один перезапрос
    /// `0x92` при битой сумме или длине, один повтор запроса при
    /// `0xD0`, повтор при полном молчании после защитного интервала.
    bool transact( const QByteArray &request, Oscill::Response &out, int guardMs );
    /// Склейка длинного ответа: части `0x48` до `0x49`, продолжение —
    /// пакетом Get выбранной формы.
    bool collectBody( Oscill::Response &first, QByteArray &body, int guardMs );

    bool readPassport();
    /// Защитный интервал для текущих настроек, мс (округление вверх).
    int guardMs() const;
    void noteMismatch( Oscill::Register reg, uint32_t wanted, uint32_t actual );
    void setError( const QString &text );

    OscillPassport m_passport;
    OscillSettings m_settings;
    std::vector< RegisterMismatch > m_mismatches;

    Oscill::Frame m_frame;
    unsigned long long m_frameSerial = 0;
    Oscill::FrameLayout m_layout = Oscill::FrameLayout::Unknown;
    Oscill::CodeSpan m_codeSpan = Oscill::CodeSpan::Unverified;
    Oscill::BodyAssembler m_assembler;
    std::vector< int > m_rollSamples;

    Oscill::Known< uint16_t > m_deviceRx;
    bool m_hasConnectionId = false;
    uint32_t m_connectionId = 0;

    bool m_checksum = false;
    bool m_continueFinal = false;
    Oscill::WriteStyle m_writeStyle = Oscill::WriteStyle::CombinedGet;

    Step m_step = Step::Offline;
    LinkStats m_stats;
};

