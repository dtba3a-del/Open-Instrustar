#pragma once

/// \file oscillbackend.h
/// \brief Прибор Oscill в дереве приборов: сессия OBEX, паспорт, настройки, кадр.
///
/// МЕСТО В ДЕРЕВЕ
///
/// Бэкенд — единственное место, где сходятся три вещи: оснастка
/// (`SerialTransport`), проводной формат (`obexcodec.h`) и знание о
/// приборе (`oscillprotocol.h`). Наверх из него выходит только
/// способность `WaveformSource` — отсчёты. Вся придурь прибора остаётся
/// здесь: приложение не должно знать ни про заголовок `0x49`, ни про то,
/// что период выборки задаётся в тактах, умноженных на 256.
///
/// ДВА СВОЙСТВА, РАДИ КОТОРЫХ ЭТОТ КОНТРАКТ ВЫГЛЯДИТ ИМЕННО ТАК
///
/// **П2. «Нет синхронизации» — валидный результат, а не ошибка.**
/// Прибор различает два разных события, и различие проходит по ДЛИНЕ
/// тела ответа, а не по коду ошибки:
///   * запуск по таймауту (`TriggerSource::Timeout` при непустом кадре) —
///     оцифровка СОСТОЯЛАСЬ, данные годны, они просто не привязаны к
///     событию синхронизации. Такой кадр показывают с пометкой;
///   * истёкший `TW` в ждущем запуске — Success с ПУСТЫМ заголовком
///     `0x49` (`Frame::empty`). Кадра нет, но связь цела.
/// Ни то, ни другое НЕ ставит `State::lastError` и не роняет
/// `state().linked`. `lastError` заполняется только при отказе линии или
/// протокола; проверять это обязан тест — иначе «нет сигнала на входе»
/// через полгода снова начнёт выглядеть как «прибор отвалился».
///
/// **П3. Прибор корректирует — клиент перечитывает.** Любая запись
/// регистра возвращает ФАКТИЧЕСКОЕ значение, прочитанное обратно, а не
/// то, что просили: прибор вправе подрезать запрошенное по своим
/// границам (`QSh`, `TDl`/`TDh`, `V1h`/`V1l`, `P1h`/`P1l`), и эти
/// границы сами меняются от других регистров. Поэтому:
///   * `writeRegister()` отдаёт факт отдельным аргументом;
///   * несовпадения складываются в `mismatches()` — их показывают, а не
///     прячут: подрезанный предел, о котором не сказали, есть враньё
///     об измерении;
///   * после записи перечитываются зависимые регистры и свойства
///     (`Oscill::dependentRegisters` / `dependentProperties`);
///   * запись предпочтительно делается СОВМЕЩЁННОЙ транзакцией
///     (`WriteStyle::CombinedGet`), в которой факт приходит тем же
///     ответом.
///
/// ТЕМП. Обычно Oscill отвечает на запрос — `Pace::OnRequest`. Но при
/// `RS` с бесконечной оцифровкой (roll) прибор гонит ленту сам, пакетами
/// `0x90 Continue`, до `Abort` со стороны хоста — а это по определению
/// `Pace::Stream`, и опрашивать такой прибор нельзя. Значит `flow()`
/// обязан считаться с текущим `RS`, а не возвращать константу; иначе
/// общий обход начнёт опрашивать прибор, который уже говорит сам.
///
/// СПОСОБНОСТЬ ОБЪЯВЛЕНА ВТОРЫМ БАЗОВЫМ КЛАССОМ, и приложение находит её
/// приведением типа. Это накладывает условие на сборку: в конфигурации
/// RELEASE приложение собирается с `-fno-rtti`, а `dynamic_cast` при
/// выключенном RTTI не компилируется вовсе. Сборка по умолчанию —
/// RelWithDebInfo, поэтому дефект молчит до первой Release-сборки. Здесь
/// он назван, а не обойдён: заводить в контракте своё «а какие у тебя
/// способности» значило бы завести второй механизм опознания рядом с
/// языковым. [СБОРКА]
///
/// СОСТОЯНИЕ УТВЕРЖДЕНИЙ. Прибора в работе нет: всё ниже — **[СБОРКА]**
/// (проверяется сборкой и прогоном против поддельного порта) либо
/// **[ПЛАН]** там, где кода ещё не существует. Ни одно число здесь не
/// перенесено со стеков ISDS205: путь A (`vdso.dll`) и путь B
/// (fx2lafw + libusb) не имеют к Oscill отношения.

