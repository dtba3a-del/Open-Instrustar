/// инициализатором в `.cpp` — нельзя: тест дерева приборов объявляет
/// `Type::Oscill` своей поддельной фабрикой и отдельно проверяет, что
/// повторное объявление отклоняется. Саморегистрация столкнётся с этой
/// проверкой, и падать начнёт тест, а не тот код, который виноват. [СБОРКА]
bool declareOscill();

