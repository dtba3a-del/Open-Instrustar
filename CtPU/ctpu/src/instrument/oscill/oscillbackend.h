/// Задержки сессии в миллисекундах. Собраны в одно место, чтобы у
/// величины не оказалось второго источника; всё, что вычисляется из
/// регистров (защитный интервал ожидания кадра), сюда НЕ входит — оно
/// считается `Oscill::captureWindowPs()`. [СБОРКА]
namespace OscillTiming {
/// Пауза после сброса `Abort` перед CONNECT. Эталонные реализации ждут
/// 500 и 300 мс; взята середина, и после паузы приёмный буфер чистится.
constexpr int RESET_SETTLE_MS = 400;
/// Сколько ждать первого байта ответа на короткий запрос (чтение
/// регистра, свойства). К оцифровке не относится: там интервал
/// вычисляется из регистров.
constexpr int SHORT_REPLY_MS = 300;
/// Сколько ждать следующей порции длинного ответа.
constexpr int CONTINUE_REPLY_MS = 300;
/// Сколько раз перезапрашивать испорченный ответ. Ровно один: первоисточник
/// говорит «однократный перезапрос», и повтор повтора маскирует
/// неисправную линию вместо того, чтобы её показать.
constexpr int REPEAT_LIMIT = 1;
} // namespace OscillTiming

/// \brief Собрать оснастку слота: порт и скорость из реестра параметров.
///
/// Фабрика реестра по контракту принимает ТОЛЬКО номер слота — иначе её
/// подпись росла бы с каждым новым прибором. Порт и скорость берутся из
/// `params.h`, группа `oscill`, ключи `port` и `baud`. **Группы этой в
/// реестре параметров сегодня нет** [ПЛАН]: до её появления функция
/// возвращает пустой указатель, и это видно сразу — `probe()` отвечает
/// «прибора нет», а `State::lastError` называет причину. Догадываться о
/// номере COM-порта функция не имеет права: открытый наугад чужой порт
/// — вмешательство в прибор, которого никто не просил.
TransportPtr makeOscillTransport( int slot );

/// \brief Объявить модель в реестре приборов. Ровно одна строка
