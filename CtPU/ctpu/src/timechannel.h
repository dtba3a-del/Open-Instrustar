// TimeChannel — время как ПОЛНОЦЕННЫЙ физический канал данных.
//
// ФИЛОСОФИЯ (решение согласовано в чате). Время перестаёт быть контекстом и
// становится каналом наравне с CH1/CH2: та же природа, те же права, та же
// философия использования. Следствия:
//   - в multi-curveXY ось времени доступна в списке осей наравне с прочими,
//     поэтому T-Y перестаёт быть выделенным режимом: это частный случай
//     XY-кривой, где одна из осей — время;
//   - «чувствительность» канала времени задаётся так же, как В/дел у
//     обычного канала, только в единицах времени: от нс/дел до ч/дел.
//     Огромный диапазон — единственное реальное отличие от CH1/CH2;
//   - экспорт и экран всегда показывают комбинацию равноправных физических
//     величин, и какая из них «пространственная», а какая «временная», для
//     механики значения не имеет.
//
// АППАРАТНАЯ ПРАВДА, которую этот класс обязан отражать честно.
// Протокол FX2 не передаёт НИКАКОЙ метки времени: хост шлёт
// CONTROL_STARTSAMPLING, чип отдаёт сырой поток байтов АЦП через
// bulk-endpoint, и рядом с данными едут только samplerate/channels/gain/tag
// (счётчик кадров, НЕ время). Поэтому время существует в двух совершенно
// разных качествах, и смешивать их — значит выдавать оценку за измерение:
//
//   t_intra — ВНУТРИ блока: index/samplerate. Жёсткая сетка, точность равна
//             стабильности задающего кварца. Это самый точный канал прибора,
//             и по разрешению он не 8-битный, а много выше.
//
//   t_epoch — МЕЖДУ блоками: момент, когда хост получил передачу. Содержит
//             недетерминированный USB-джиттер порядка миллисекунд. Для
//             медленных развёрток (самописец) пренебрежимо; для сшивки
//             быстрых кадров — принципиально неустранимо ЭТИМ железом.
//
// Класс хранит обе величины раздельно и НИКОГДА не притворяется, что вторая
// точна. Полное время отсчёта = epoch блока + intra внутри блока, и
// вызывающий код всегда может узнать, какая часть измерена, а какая оценена.

#pragma once

#include <cmath>
#include <cstdint>
#include <string>
#include <vector>

namespace TimeChannel {

/// \brief Отсчёт времени с явным разделением измеренного и оценочного.
struct Stamp {
    /// Точное время от начала блока, с. Измерено (index/samplerate).
    double intra = 0.0;
    /// Оценочное время начала блока (host wall-clock), с. USB-джиттер.
    double epoch = 0.0;

    /// Полное время. Точность ограничена оценочной составляющей — см.
    /// epochIsEstimate(): при сравнении отсчётов ВНУТРИ одного блока
    /// используйте intra, он на порядки точнее.
    double total() const { return epoch + intra; }

    /// Всегда true: в этом классе приборов аппаратной метки времени нет,
    /// epoch принципиально является оценкой. Метод существует, чтобы
    /// вызывающий код документировал это явно, а не подразумевал.
    static constexpr bool epochIsEstimate() { return true; }
};

/// \brief Точное внутриблочное время отсчёта с индексом index.
static inline double intraTime( std::size_t index, double sampleRateHz ) {
    return sampleRateHz > 0.0 ? double( index ) / sampleRateHz : 0.0;
}

/// \brief Ряд точных внутриблочных времён для целого блока.
static inline std::vector< double > intraTimeSeries( std::size_t count, double sampleRateHz ) {
    std::vector< double > t;
    t.reserve( count );
    for ( std::size_t i = 0; i < count; ++i )
        t.push_back( intraTime( i, sampleRateHz ) );
    return t;
}

/// \name Чувствительность канала времени (аналог В/дел)
///
/// Ряд 1-2-5, как принято для вертикальных пределов в измерительной технике
/// (логарифмически равномерный шаг; та же причина, по которой так устроены
/// В/дел и денежные номиналы). Диапазон от 1 нс/дел до 1 ч/дел покрывает всё,
/// что этот прибор способен зафиксировать: от предела дискретизации до
/// многочасовой записи самописца.
///@{

/// Полный ряд значений «время/деление», в секундах.
static inline const std::vector< double > &divisionSteps() {
    static const std::vector< double > steps = {
        1e-9,  2e-9,  5e-9,  1e-8,  2e-8,  5e-8,  1e-7, 2e-7, 5e-7, 1e-6, 2e-6, 5e-6, 1e-5, 2e-5, 5e-5,
        1e-4,  2e-4,  5e-4,  1e-3,  2e-3,  5e-3,  1e-2, 2e-2, 5e-2, 0.1,  0.2,  0.5,  1.0,  2.0,  5.0,
        10.0,  20.0,  30.0,  60.0,          // с -> мин
        120.0, 300.0, 600.0, 1800.0, 3600.0 // мин -> ч
    };
    return steps;
}

/// \brief Ближайшее стандартное значение «время/деление», не меньше желаемого.
/// Возвращает максимальное из ряда, если желаемое превышает весь диапазон.
static inline double snapDivision( double desiredSecPerDiv ) {
    const auto &steps = divisionSteps();
    for ( double s : steps )
        if ( s >= desiredSecPerDiv )
            return s;
    return steps.back();
}

/// \brief Человекочитаемая подпись «время/деление» с приставкой СИ.
/// Единица базовая (секунда), приставка выбирается по величине — та же
/// конвенция, что и для остальных каналов (см. printutils.cpp), поэтому
/// поле единицы канала времени должно содержать "s", а не "ms"/"us".
static inline std::string divisionLabel( double secPerDiv ) {
    struct P {
        double factor;
        const char *prefix;
    };
    static const P table[] = { { 1e-9, "n" }, { 1e-6, "u" }, { 1e-3, "m" }, { 1.0, "" } };
    if ( secPerDiv >= 3600.0 )
        return std::to_string( long( std::lround( secPerDiv / 3600.0 ) ) ) + " h";
    if ( secPerDiv >= 60.0 )
        return std::to_string( long( std::lround( secPerDiv / 60.0 ) ) ) + " min";
    for ( const P &p : table ) {
        if ( secPerDiv < p.factor * 1000.0 ) {
            const double v = secPerDiv / p.factor;
            // Ряд 1-2-5 даёт целые мантиссы, поэтому дробная часть не нужна.
            return std::to_string( long( std::lround( v ) ) ) + " " + p.prefix + "s";
        }
    }
    return std::to_string( long( std::lround( secPerDiv ) ) ) + " s";
}
///@}

} // namespace TimeChannel
