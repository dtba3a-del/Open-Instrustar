// В каком классе драйвера находится дескриптор устройства.
//
// Замечание автора 2026-09-05, по снимкам диспетчера устройств:
//
// > «процесс (выберите устройство), находя дескриптор устройства в своём
// > списке, тупо вливает прошивку, не проверяя класс (winusb or libusb?).
// > Такое поведение НИКОГДА не достигнет работоспособного состояния VDSO.
// > Работоспособная система при запуске приложения CtPU снова оказывается с
// > неработоспособным драйвером, перепрошитым в fx2lafw по-тихому. Это
// > недопустимо.»
//
// Правило, названное автором:
//
//     libusb  → запись прошивки fx2lafw РАЗРЕШЕНА  (режим openhantek, путь B)
//     winusb  → запись прошивки fx2lafw ЗАПРЕЩЕНА  (режим instrustar, путь A)
//
// **Почему запись «проходит», хотя прибор под вендорским драйвером.**
// Заливка идёт управляющими передачами в ядро FX2 — WinUSB их пропускает.
// Прибор принимает прошивку в оперативку и перечисляется заново уже как
// `1d50:608e`, для которого в системе драйвера нет. В итоге не работает
// НИ ОДИН путь: вендорский стек потерял свой `d4a2:566x`, а наш не может
// взять устройство, которому никто не назначен. Именно это на снимках
// автора видно как `fx2lafw` в разделе «Другие устройства» с восклицательным
// знаком. Повторное включение прибора возвращает всё на место: прошивка
// живёт в оперативке.
//
// Отсюда: «прошивка не пишется под вендорским драйвером» — формулировка
// неточная. Пишется. Результат — устройство, которым не может пользоваться
// никто, и это хуже отказа.

#pragma once

#include <QString>
#include <cstdint>

namespace UsbDriverClass {

enum class Class {
    Unknown,          ///< опознать не удалось (не Windows, устройства нет, доступа нет)
    VendorInstruStar, ///< драйвер вендора: `YiXingDianZi USB DSO(vN) Driver` — путь A
    LibusbFamily,     ///< WinUSB/libusbK/libusb0, поставленный Zadig — путь B
};

struct Verdict {
    Class cls = Class::Unknown;
    QString service;     ///< служба драйвера: WINUSB, libusbK, libusb0 …
    QString description; ///< описание устройства из системы
};

/// Опрашивает систему о дескрипторе `vid:pid`.
/// Под Windows — через SetupAPI; на других системах всегда Unknown.
Verdict forDevice( uint16_t vid, uint16_t pid );

/// Разрешена ли запись прошивки fx2lafw.
///
/// **Отказ выносится только при положительном опознании вендорского
/// драйвера.** Неизвестность не запрещает: иначе на всякой машине, где
/// опознание не сработало, перестал бы работать путь B — а это отказ от
/// собственной задачи ради предположения. Зато при опознанном вендорском
/// драйвере отказ безусловен: там запись рушит рабочее состояние.
bool firmwareWriteAllowed( const Verdict &v );

/// Почему отказано — текстом для оператора, а не кодом.
QString explain( const Verdict &v );

} // namespace UsbDriverClass
