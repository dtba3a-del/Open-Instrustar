#pragma once

/// \file params.h
/// \brief Реестр параметров: настройка объявляется ОДИН раз.
///
/// ЗАЧЕМ ЭТО ЗАВЕДЕНО
///
/// До реестра одна настройка жила в пяти местах: поле в `scopesettings.h`,
/// чтение и запись в `dsosettings.cpp`, страница диалога, виджет дока и
/// (для аппаратных) спецификация модели. Пять мест — пять поводов
/// разойтись, и они расходились:
///
///   * AC: список видов связи строился один раз в конструкторе дока и
///     нигде не пересобирался. Галка в диалоге меняла настройку, список —
///     нет. На галке было честно написано «restart needed». Пользователь
///     находил настройку, ставил и не получал ничего; поиски уходили
///     вплоть до реестра Windows (2026-08-22).
///   * `couplingOrMathIndex` — одно поле с ДВУМЯ смыслами: вид связи у
///     реальных каналов и режим у математического. Имя признаёт коллизию,
///     хранится под одним ключом.
///
/// Цена таких ошибок — не сама правка, а то, что каждая новая функция
/// тянет за собой обвязку в пяти файлах. Это и есть главный тормоз
/// строительства, а не сложность самих функций.
///
/// КАК ЭТО РАБОТАЕТ
///
/// Параметр — это ОБЪЯВЛЕНИЕ: ключ хранения, вид, подпись, единица,
/// границы, подсказка, плюс пара функций доступа к полю настроек.
/// По объявлению строится всё остальное:
///
///   * чтение и запись в `QSettings` — обходом реестра, а не руками;
///   * элемент управления в интерфейсе — по виду и границам;
///   * проверка допустимости — по границам, в одном месте.
///
/// Добавить настройку = добавить строку сюда. Ничего больше.
///
/// ПОРЯДОК МИГРАЦИИ
///
/// Реестр вводится не переписыванием всего разом (это была бы та самая
/// переделка, которой избегаем), а по группам: группа переезжает тогда,
/// когда её всё равно трогают. Первой переехала группа `ctpu` — перевод
/// канала в физические единицы, главная функция прибора. Непереехавшие
/// настройки продолжают работать по-старому и никак не затронуты.

#include <QString>
#include <QVariant>
#include <functional>
#include <vector>

#include "hantekprotocol/types.h"

struct DsoSettingsScope;

namespace Params {

/// Вид параметра — определяет и элемент управления, и проверку.
enum class Kind {
    Bool,   ///< галка
    Int,    ///< целое в границах [min; max]
    Real,   ///< вещественное в границах [min; max]
    Text,   ///< короткая строка (единица измерения и т.п.)
    Choice, ///< выбор из перечня `choices`
};

/// Объявление параметра. Единственное место, где настройка описана.
struct Def {
    QString group;   ///< группа: по ней собирается один экран/попап
    QString key;     ///< ключ хранения, стабильный: менять нельзя
    Kind kind;
    QString label;   ///< подпись в интерфейсе
    QString unit;    ///< единица подписи (пусто, если неприменимо)
    double min = 0;  ///< граница для Int/Real
    double max = 0;  ///< граница для Int/Real
    int decimals = 3;             ///< знаков после запятой для Real
    QStringList choices;          ///< варианты для Choice
    QString tip;                  ///< подсказка
    bool perChannel = true;       ///< параметр свой у каждого канала
    QVariant defaultValue;        ///< значение по умолчанию

    /// Доступ к полю настроек. Держим функциями, а не смещениями: поля
    /// разных групп лежат в разных структурах, и никакой общей базы у них
    /// нет — навязывать её ради реестра было бы переделкой ради реестра.
    std::function< QVariant( const DsoSettingsScope &, ChannelID ) > get;
    std::function< void( DsoSettingsScope &, ChannelID, const QVariant & ) > set;
};

/// \brief Все объявленные параметры. Единственный источник истины.
const std::vector< Def > &registry();

/// \brief Параметры одной группы, в порядке объявления.
std::vector< const Def * > group( const QString &name );

/// \brief Привести значение к границам объявления.
/// Проверка живёт здесь, а не в каждом обработчике: разъехавшиеся
/// проверки — тот же класс ошибок, что и разъехавшиеся списки.
QVariant clamp( const Def &def, const QVariant &value );

} // namespace Params
