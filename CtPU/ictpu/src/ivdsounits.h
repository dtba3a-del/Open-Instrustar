// Путь A: приведение величин между языком CtPU и языком vdso.
//
// Весь пересчёт единиц собран здесь и только здесь. Причина — правило
// проекта о двоевластии параметров (`docs/ДВОЕВЛАСТИЕ.md`): величина
// имеет одно место, которое её порождает. Множитель ×1000 живёт на пути
// НАСТРОЕК (предел канала задаётся в милливольтах) и не должен появиться
// на пути ДАННЫХ (ReadVoltageDatas отдаёт double, см. ivdsounits.cpp).
//
// Файл не зависит ни от Qt, ни от Windows: он проверяется тестами на
// любой машине, без прибора и без DLL.

#pragma once

#include <cstdint>
#include <string>
#include <vector>

namespace IVdso {

/// Предел канала так, как его принимает вендор: интервал в милливольтах.
struct RangeMv {
    int minMv = 0;
    int maxMv = 0;

    bool operator==( const RangeMv &o ) const { return minMv == o.minMv && maxMv == o.maxMv; }
};

/// Число делений по вертикали в представлении CtPU. Значение то же, что
/// DIVS_VOLTAGE в `ctpu/src/viewconstants.h`; здесь оно повторено НЕ как
/// второй источник, а как параметр по умолчанию — вызывающий обязан
/// передать своё, если работает в другом представлении.
constexpr int DEFAULT_DIVS_VOLTAGE = 8;

/// «В/дел» представления CtPU → предел вендора в милливольтах.
/// Окно симметрично: смещения канала в API пути A нет вовсе (ни одной
/// функции среди 73), несимметричное окно — единственный его аналог и
/// на приборе не проверено.
RangeMv rangeMvFromVoltsPerDiv( double voltsPerDiv, int divsVoltage = DEFAULT_DIVS_VOLTAGE );

/// Предел вендора → «В/дел» представления CtPU. Обратна предыдущей на
/// симметричном окне; на несимметричном берёт половину размаха.
double voltsPerDivFromRangeMv( const RangeMv &range, int divsVoltage = DEFAULT_DIVS_VOLTAGE );

/// Память и длина захвата печатаются вендором В КИЛОБАЙТАХ, а «байт»
/// здесь равен одному отсчёту на канал: оба демо вендора выделяют
/// GetMemoryLength()*1024 элементов double.
unsigned int pointsFromKb( unsigned int kb );
/// Отсчёты → КБ с округлением ВВЕРХ: запросить меньше запрошенного нельзя.
unsigned int kbFromPoints( unsigned int points );

/// Ближайшая поддерживаемая скорость из ряда прибора.
/// Ряд у ISDS205B: 1M, 4M, 8M, 16M, 48M Sps — произвольное значение
/// прибор не примет, а SetOscSample об отказе сообщает нулём, когда
/// поздно. Пустой ряд → 0.
unsigned int nearestSupportedSamplerate( unsigned int requested,
                                         const std::vector< unsigned int > &supported );

/// Уникальный номер прибора: два слова одного 64-битного числа,
/// а не два независимых числа (VdsoLib.h: "only id(0-31)"/"(32-63)").
uint64_t deviceId( unsigned int id0, unsigned int id1 );

/// Имя модели по максимуму ряда скоростей и наличию DDS. Функции
/// «спросить модель» в API нет; это единственный доступный признак.
std::string modelName( unsigned int sampleRateMax, bool hasDds );

/// Разрядность АЦП по имени модели (у 2062 — 12 бит, у остальных 8).
int adcBits( const std::string &model );

/// Признак насыщения приходит на канал отдельным вызовом
/// IsVoltageDatasOutRange, потому что после пересчёта в вольты
/// «код 0 или 255» уже неразличим.
bool clipped( int isVoltageDatasOutRangeReturn );

/// Сколько отсчётов взять от двух каналов. Каналы возвращают РАЗНОЕ
/// число: на 205A/B при пределах ≥2000 мВ на запрос 4096 приходит 2044.
/// Всё, что считает по длине окна, обязано брать это число, а не
/// запрошенное.
unsigned int commonLength( unsigned int nCh1, unsigned int nCh2 );

/// Разность сырых кодов АЦП, восстановленная из пересчитанных значений.
/// Внутри библиотеки отсчёт получается как code*resolution + bias, где
/// bias наружу не выставлен; значит разность кодов восстанавливается
/// точно, а сам код — нет. resolution ≤ 0 → 0.
double codeDifference( double v1, double v2, double resolution );

/// Правдоподобие шага квантования при заданном пределе.
///
/// Величина без установленной единицы в конвейер не идёт. Заголовок
/// вендора объявляет данные в вольтах, MFC-демо того же вендора рисует
/// тот же буфер на милливольтовой оси. Расхождение снимается ОДНИМ
/// измерением на приборе, а до него коннектор обязан отказать вслух, а
/// не построить молча кривой график.
///
/// Проверка: шаг, умноженный на полную шкалу кода (2^bits), обязан
/// лечь в тот же порядок, что и заявленное окно канала.
/// tolerance — во сколько раз допустимо разойтись (по умолчанию 4×).
bool resolutionPlausible( double resolution, const RangeMv &range, int bits,
                          double sampleToVolt, double tolerance = 4.0 );

/// Множитель приведения отсчёта пути A к вольтам конвейера CtPU.
///
/// ЕДИНСТВЕННОЕ место, где путь A приводится к вольтам. Значение 1.0
/// стоит по заголовку вендора ("read the voltage datas. (V)") и по
/// измерениям пути A из `references/path-a-prototype/measurements/`,
/// где размах открытого входа сходится с шагом квантования только в
/// вольтах. Установить его окончательно может лишь измерение на
/// приборе (известная амплитуда → max(buf)); до него значение
/// охраняется resolutionPlausible().
constexpr double SAMPLE_TO_VOLT = 1.0;

/// Имя файла калибровки обязано нести метку стека: калибровка пути A
/// (заводская, из EEPROM прибора, разная по каналам) и калибровка пути
/// B (наша, построенная процедурой) — разные величины, и совпадение
/// имени файла подменило бы одну другой молча.
std::string calibrationFileName( const std::string &model, uint64_t id );

} // namespace IVdso
